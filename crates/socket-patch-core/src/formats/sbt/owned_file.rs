//! The generated sbt files: `socket-patch.sbt` (hosted, `get`) and
//! `socket-patch-vendor.sbt` (vendored, `vendor`), one model for both.
//!
//! Each file holds:
//! - a `@ID@Pins` table, two rows per pin (pom, then jar): coordinates, the
//!   suffixed version, the repo-relative path, the sha256 and the source URL
//!   (`""` when vendored);
//! - the shared helpers (`@ID@Fail`, `@ID@Sha256`, `@ID@Verify`), all carrying
//!   the `@ID@` prefix because top-level names are shared across a project's
//!   `.sbt` files; `@ID@Newer` compares two versions by their leading
//!   numbers, as `formats::sbt::build::numeric_newer` does;
//! - `Global / @ID@Rows`, publishing the table to the other file's installer;
//! - inside `inThisBuild(…)`, a resolver for the pin repository
//!   (`.socket/sbt-hosted/maven2`, which the hosted file fills at load from
//!   the pinned URLs and gitignores, or the committed `.socket/vendor/maven2`
//!   tree) and one `dependencyOverrides +=` per pin forcing
//!   `<base>-socket.<hex8>`;
//! - a `Global / onLoad` installer wrapping every project's `update` with the
//!   verifier V: no project may declare a pinned GA at a version newer than
//!   the pin's base (the override would force it back down; a dynamic
//!   version is not compared), each non-evicted pinned module must resolve
//!   the pinned version, and each of its artifacts must hash to one of that
//!   GA's pinned sha256s. Both files share the marker label `socketPatchApplied`, so
//!   whichever loads first installs one V over both files' rows.
//!
//! The bytes are frozen by the sbt template probe
//! (`docs/design/sbt-template-probe.md`, six sbt versions); [`render`] is
//! byte-identical to the probe's reference renderer, and the golden fixtures
//! under `tests/fixtures/sbt/owned_file/` are the probe's own renders. The
//! three syntax lines ([`SbtLine`]) differ only in the `@ID@Rows` setting
//! line and the installer.
//!
//! [`parse`] is strict: anything but bytes [`render`] would write, modulo
//! CRLF, is [`OwnedFileError::Modified`]. A file without the socket-patch
//! header is [`OwnedFileError::Foreign`].
//!
//! [`validate_values`] guards every value written into the template's Scala
//! string literals (always plain `"…"`, never `s"…"`), so each must be safe
//! there unescaped.

