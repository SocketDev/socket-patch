    /// The rows and overrides of `text`, in file order.
    fn regions(text: &str) -> (Vec<String>, Vec<String>) {
        let pick = |prefix: &str| {
            text.lines()
                .filter(|l| l.starts_with(prefix))
                .map(str::to_string)
                .collect()
        };
        (pick("  (\""), pick("  dependencyOverrides"))
    }

    /// The file of `mode`/`line` holding exactly `rows` and `overrides`,
    /// commas re-placed so only the edit under test is wrong.
    fn assemble(mode: SbtFileMode, line: SbtLine, rows: &[String], ovs: &[String]) -> String {
        let recomma = |lines: &[String]| {
            let items: Vec<(String, String)> = lines
                .iter()
                .map(|l| {
                    let (code, comment) = l.split_once(" // socket-patch ").expect("comment");
                    (code.trim_end_matches(',').to_string(), comment.to_string())
                })
                .collect();
            join_lines(&items)
        };
        template(mode, line)
            .replace(ROWS, &recomma(rows))
            .replace(OVERRIDES, &recomma(ovs))
    }

