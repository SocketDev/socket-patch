/// The hosted file, at the build root.
pub const HOSTED_FILE: &str = "socket-patch.sbt";
/// The vendored file, at the build root.
pub const VENDORED_FILE: &str = "socket-patch-vendor.sbt";
/// Where the hosted file downloads its pins (gitignored by the file itself).
pub const HOSTED_REPO_REL: &str = ".socket/sbt-hosted/maven2";
/// The vendored (committed, suffixed) tree.
pub const VENDORED_REPO_REL: &str = layout::MAVEN2_TREE;
/// The first line of every generated file (and the ownership test).
pub const HEADER_PREFIX: &str = "// Generated by socket-patch";

/// Which command owns the file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SbtFileMode {
    Hosted,
    Vendored,
}

impl SbtFileMode {
    /// The file's root-relative path.
    pub fn file(self) -> &'static str {
        match self {
            SbtFileMode::Hosted => HOSTED_FILE,
            SbtFileMode::Vendored => VENDORED_FILE,
        }
    }

    /// The pin repository, root-relative.
    pub fn repo_rel(self) -> &'static str {
        match self {
            SbtFileMode::Hosted => HOSTED_REPO_REL,
            SbtFileMode::Vendored => VENDORED_REPO_REL,
        }
    }

    /// The template constants: (command, identifier prefix, `.socket/` dir,
    /// resolver name).
    fn consts(self) -> (&'static str, &'static str, &'static str, &'static str) {
        match self {
            SbtFileMode::Hosted => ("get", "socketPatchHosted", "sbt-hosted", "socket-patch"),
            SbtFileMode::Vendored => (
                "vendor",
                "socketPatchVendor",
                "vendor",
                "socket-patch-vendor",
            ),
        }
    }
}

/// One pinned patch: two rows (pom, jar) and one override in the file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SbtPin {
    pub uuid: String,
    pub group: String,
    pub artifact: String,
    /// The upstream version the patch applies to.
    pub base: String,
    /// `<base>-socket.<first 8 hex of the uuid>`.
    pub sv: String,
    /// Bare lowercase sha256 hex of the served pom / jar (a `sha256-` /
    /// `sha256:` prefix is accepted and dropped on render).
    pub pom_sha256: String,
    pub jar_sha256: String,
    /// [`super::build::deps_digest`] when the pin was written.
    pub deps_digest: String,
    /// The hosted maven2 index URL the rows' sources live under; `None` for
    /// a vendored pin.
    pub index_url: Option<String>,
}

impl SbtPin {
    /// The pom (`ext == "pom"`) or jar path of this pin, relative to the pin
    /// repository.
    pub fn repo_path(&self, ext: &str) -> String {
        layout::artifact_path(&self.group, &self.artifact, &self.sv, None, ext)
    }
}

/// A parsed (or to-be-rendered) generated file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SbtOwnedFile {
    pub mode: SbtFileMode,
    pub line: SbtLine,
    /// The file uses `\r\n` line endings (kept on re-render).
    pub crlf: bool,
    /// Pins by uuid.
    pub pins: BTreeMap<String, SbtPin>,
}

/// Why a generated-file path does not hold a file socket-patch can own.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OwnedFileError {
    /// The header is socket-patch's, the rest is not what it writes.
    Modified(String),
    /// No socket-patch header: a user's own file under our name (the
    /// remedy is to rename it, never `git checkout`).
    Foreign,
}

/// Why [`render`] refused a model. Callers validate first; this is the
/// last guard before bytes reach a Scala file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenderError {
    /// Zero pins are never rendered (the last-out path deletes the file;
    /// an empty `Seq(…)` tail is invalid Scala 2.10).
    NoPins,
    /// A pin is unsafe or inconsistent with the file's mode.
    Invalid { uuid: String, reason: &'static str },
}

/// The shared body. `@ROWS@` / `@OVERRIDES@` are filled per file;
/// `@ROWS_SETTING@`, `@GITIGNORE@` and the constants per mode and line.
/// `@GITIGNORE@` is the whole hosted line (with its newline) or nothing.
const BODY: &str = r##"// Generated by socket-patch. Do not edit; re-run `socket-patch @CMD@`.
val @ID@Pins = Seq[(String, String, String, String, String, String)](
  // (group, artifact, socket version, repo-relative path, sha256, source URL; "" = vendored)
@ROWS@
)
val @ID@Rows = SettingKey[Seq[(String, String, String, String, String, String)]]("@ID@Rows")
val @ID@Applied = SettingKey[Boolean]("socketPatchApplied")
def @ID@Fail(m: String): Nothing = sys.error("socket-patch: " + m + ". Re-run `socket-patch @CMD@`.")
def @ID@Sha256(f: java.io.File): String = java.security.MessageDigest.getInstance("SHA-256")
  .digest(java.nio.file.Files.readAllBytes(f.toPath)).map(b => "%02x".format(b & 0xff)).mkString
def @ID@Newer(v: String, base: String): Boolean = {
  def nums(s: String): Seq[BigInt] = "^[0-9]+(\\.[0-9]+)*".r.findFirstIn(s.trim).toSeq.flatMap(_.split('.')).map(n => BigInt(n))
  nums(v).zipAll(nums(base), BigInt(0), BigInt(0)).find(t => t._1 != t._2).exists(t => t._1 > t._2)
}
def @ID@Verify(p: String, pins: Seq[(String, String, String, String, String, String)], deps: Seq[ModuleID], r: UpdateReport): UpdateReport = {
  deps.foreach { d => pins.find(x => x._1 == d.organization && (x._2 == d.name || x._2.startsWith(d.name + "_"))).foreach { case (g, a, sv, _, _, _) =>
    val base = sv.substring(0, sv.lastIndexOf("-socket."))
    if (!d.revision.exists(c => "+[](),".indexOf(c) >= 0) && !d.revision.startsWith("latest.") && @ID@Newer(d.revision, base)) @ID@Fail(p + " declares " + g + ":" + a + ":" + d.revision + " but socket-patch forces " + sv + " (a downgrade); roll the patch back, or declare " + base)
  } }
  r.configurations.foreach { c => c.modules.filter(!_.evicted).foreach { m =>
    val mine = pins.filter(x => x._1 == m.module.organization && x._2 == m.module.name)
    mine.headOption.foreach { case (g, a, sv, _, _, _) =>
      if (m.module.revision != sv) @ID@Fail(p + " resolves " + g + ":" + a + ":" + m.module.revision + ", expected " + sv + "; a dependencyOverrides := or resolver change in the build replaced socket-patch's")
      m.artifacts.foreach { case (_, f) =>
        val got = @ID@Sha256(f)
        if (!mine.exists(_._5 == got)) @ID@Fail(g + ":" + a + ":" + sv + " resolved to " + f + " with sha256 " + got + ", which is not pinned (tampered, or from ivy-local, mavenLocal or another checkout); delete it and run sbt update")
      }
    }
  } }
  r
}
@ROWS_SETTING@
inThisBuild(Seq(
  resolvers += {
    val repo = new java.io.File(baseDirectory.value, ".socket/@DIR@/maven2").getCanonicalFile
@GITIGNORE@    @ID@Pins.foreach { case (_, _, _, rel, want, src) =>
      val f = new java.io.File(repo, rel)
      if (!f.isFile || @ID@Sha256(f) != want) {
        if (src.isEmpty) @ID@Fail(if (f.isFile) "" + f + " has sha256 " + @ID@Sha256(f) + ", pinned " + want else "missing " + f)
        f.getParentFile.mkdirs()
        val tmp = java.io.File.createTempFile("socket-patch", ".part", f.getParentFile)
        try {
          try {
            val c = new java.net.URL(src).openConnection(); c.setConnectTimeout(30000); c.setReadTimeout(120000)
            val in = c.getInputStream
            try java.nio.file.Files.copy(in, tmp.toPath, java.nio.file.StandardCopyOption.REPLACE_EXISTING) finally in.close()
          } catch { case e: java.io.IOException => @ID@Fail("cannot download " + src + " (" + e + ")") }
          val got = @ID@Sha256(tmp)
          if (got != want) @ID@Fail("" + src + " served sha256 " + got + ", pinned " + want)
          java.nio.file.Files.move(tmp.toPath, f.toPath, java.nio.file.StandardCopyOption.REPLACE_EXISTING)
        } finally tmp.delete()
      }
    }
    "@RESOLVER@" at repo.toURI.toString
  },
@OVERRIDES@
))
"##;

/// The hosted-only line writing `.socket/sbt-hosted/.gitignore` (`*`). A
/// plain statement: a `{` block on its own line would parse as an argument
/// to the previous call.
const GITIGNORE: &str = r#"    val gitignore = new java.io.File(repo.getParentFile, ".gitignore"); if (!gitignore.isFile) { repo.mkdirs(); java.nio.file.Files.write(gitignore.toPath, "*\n".getBytes) }
"#;

