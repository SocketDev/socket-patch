    #[test]
    fn validate_values_rejects_every_unsafe_value() {
        type Mutate = fn(&mut SbtPin);
        let cases: Vec<(Mutate, &str)> = vec![
            (|p| p.uuid = "not-a-uuid".into(), "uuid"),
            (|p| p.uuid = UUID.to_uppercase(), "uuid"),
            (|p| p.group = "org.ex\"ample".into(), "coordinates"),
            (|p| p.group = "org/apache".into(), "coordinates"),
            (|p| p.group = "org..apache".into(), "coordinates"),
            (|p| p.artifact = "a$b".into(), "coordinates"),
            (|p| p.artifact = "..".into(), "coordinates"),
            (|p| p.artifact = "a--b".into(), "coordinates"),
            (|p| p.artifact = "a\\b".into(), "coordinates"),
            (|p| p.base = "1 0".into(), "coordinates"),
            (|p| p.base = "latest.release".into(), "coordinates"),
            (|p| p.base = "1.0+".into(), "coordinates"),
            (|p| p.sv = "3.11-socket.00000000".into(), "suffixed"),
            (|p| p.sv = "3.11".into(), "suffixed"),
            (|p| p.pom_sha256 = "a".repeat(63), "sha256"),
            (|p| p.jar_sha256 = "z".repeat(64), "sha256"),
            (
                |p| p.jar_sha256 = format!("md5-{}", "a".repeat(64)),
                "sha256",
            ),
            (|p| p.deps_digest = "ABCDEF01".into(), "digest"),
            (|p| p.deps_digest = "abc".into(), "digest"),
            (
                |p| p.index_url = Some("https://x/\"+sys.exit()+\"".into()),
                "URL",
            ),
            (|p| p.index_url = Some("file:///etc".into()), "URL"),
            (|p| p.index_url = Some("https://x/${HOME}".into()), "URL"),
            (|p| p.index_url = Some("https://x/a b".into()), "URL"),
            (|p| p.index_url = Some("https://x/\\u0022".into()), "URL"),
            (|p| p.index_url = Some("https://x/\n".into()), "URL"),
        ];
        for (mutate, why) in cases {
            let mut p = pin();
            mutate(&mut p);
            let err = validate_values(&p).expect_err(why);
            assert!(err.contains(why), "{why}: {err}");
        }
    }

