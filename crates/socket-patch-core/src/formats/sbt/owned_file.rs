const ROWS: &str = "@ROWS@";
const OVERRIDES: &str = "@OVERRIDES@";

/// The full LF template for `mode` and `line`, with only `@ROWS@` and
/// `@OVERRIDES@` left (the probe's `.sbt.tpl` files).
fn template(mode: SbtFileMode, line: SbtLine) -> String {
    let (cmd, id, dir, resolver) = mode.consts();
    let (rows_setting, install) = match line {
        SbtLine::Sbt013 => ("@ID@Rows in Global := @ID@Pins", INSTALL_013),
        SbtLine::Sbt1 => ("Global / @ID@Rows := @ID@Pins", INSTALL_1),
        SbtLine::Sbt2 => ("Global / @ID@Rows := @ID@Pins", INSTALL_2),
    };
    let gitignore = match mode {
        SbtFileMode::Hosted => GITIGNORE,
        SbtFileMode::Vendored => "",
    };
    format!("{}{install}", BODY.replace("@ROWS_SETTING@", rows_setting))
        .replace("@RESOLVER@", resolver)
        .replace("@GITIGNORE@", gitignore)
        .replace("@CMD@", cmd)
        .replace("@ID@", id)
        .replace("@DIR@", dir)
}

/// The `src` column of a row: `<index>/<rel>` hosted, `""` vendored.
fn source_url(pin: &SbtPin, rel: &str) -> String {
    pin.index_url
        .as_deref()
        .map_or_else(String::new, |index| format!("{index}/{rel}"))
}

/// `items` joined one per line, `,` on every line but the last, then the
/// trailing `// socket-patch <comment>`.
fn join_lines(items: &[(String, String)]) -> String {
    let last = items.len().saturating_sub(1);
    items
        .iter()
        .enumerate()
        .map(|(i, (code, comment))| {
            let comma = if i < last { "," } else { "" };
            format!("{code}{comma} // socket-patch {comment}")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Whether `pin` may go into a file of `mode`, beyond [`validate_values`].
fn check_mode(mode: SbtFileMode, pin: &SbtPin) -> Result<(), &'static str> {
    match (mode, pin.index_url.as_deref()) {
        (SbtFileMode::Hosted, None) => Err("hosted pin has no index URL"),
        (SbtFileMode::Hosted, Some(url)) if !url.contains(&pin.uuid) => {
            Err("index URL does not name the patch uuid")
        }
        (SbtFileMode::Vendored, Some(_)) => Err("vendored pin has an index URL"),
        _ => Ok(()),
    }
}

/// The file's exact bytes for `f`: rows and overrides sorted by
/// `(group, artifact, sv)`, hashes bare, `\r\n` when `f.crlf`.
///
/// Refuses (never renders) zero pins, a pin keyed under another uuid, a pin
/// failing [`validate_values`] or its mode's URL rule, and two pins for one
/// `group:artifact` (one file forces one version per GA; callers replace or
/// refuse before rendering).
pub fn render(f: &SbtOwnedFile) -> Result<String, RenderError> {
    if f.pins.is_empty() {
        return Err(RenderError::NoPins);
    }
    let invalid = |p: &SbtPin, reason| RenderError::Invalid {
        uuid: p.uuid.clone(),
        reason,
    };
    let mut pins: Vec<&SbtPin> = Vec::with_capacity(f.pins.len());
    for (key, p) in &f.pins {
        if *key != p.uuid {
            return Err(invalid(p, "pin is keyed under another uuid"));
        }
        validate_values(p).map_err(|reason| invalid(p, reason))?;
        check_mode(f.mode, p).map_err(|reason| invalid(p, reason))?;
        pins.push(p);
    }
    pins.sort_by(|x, y| (&x.group, &x.artifact, &x.sv).cmp(&(&y.group, &y.artifact, &y.sv)));
    if let Some(w) = pins
        .windows(2)
        .find(|w| (&w[0].group, &w[0].artifact) == (&w[1].group, &w[1].artifact))
    {
        return Err(invalid(w[1], "two pins for one group:artifact"));
    }

    let mut rows = Vec::with_capacity(pins.len() * 2);
    let mut overrides = Vec::with_capacity(pins.len());
    for p in pins {
        for (ext, sha) in [("pom", &p.pom_sha256), ("jar", &p.jar_sha256)] {
            let rel = p.repo_path(ext);
            rows.push((
                format!(
                    "  (\"{}\", \"{}\", \"{}\", \"{rel}\", \"{}\", \"{}\")",
                    p.group,
                    p.artifact,
                    p.sv,
                    bare_sha256(sha),
                    source_url(p, &rel)
                ),
                p.uuid.clone(),
            ));
        }
        overrides.push((
            format!(
                "  dependencyOverrides += \"{}\" % \"{}\" % \"{}\"",
                p.group, p.artifact, p.sv
            ),
            format!("{} deps={}", p.uuid, p.deps_digest),
        ));
    }
    let text = template(f.mode, f.line)
        .replace(ROWS, &join_lines(&rows))
        .replace(OVERRIDES, &join_lines(&overrides));
    Ok(if f.crlf {
        text.replace('\n', "\r\n")
    } else {
        text
    })
}

static ROW: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r#"^  \("([^"]*)", "([^"]*)", "([^"]*)", "([^"]*)", "([0-9a-f]{64})", "([^"]*)"\)(,?) // socket-patch ([0-9a-f-]{36})$"#,
    )
    .expect("row regex")
});

static OVERRIDE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r#"^  dependencyOverrides \+= "([^"]*)" % "([^"]*)" % "([^"]*)"(,?) // socket-patch ([0-9a-f-]{36}) deps=([0-9a-f]{8})$"#,
    )
    .expect("override regex")
});

/// One parsed row.
struct Row<'t> {
    group: &'t str,
    artifact: &'t str,
    sv: &'t str,
    rel: &'t str,
    sha256: &'t str,
    src: &'t str,
    uuid: &'t str,
}

/// Lines of a region between fixed text, each matched by `re`, with the
/// comma rule checked: `,` (capture `comma`) on every line but the last.
fn region_lines<'t>(
    region: &'t str,
    re: &Regex,
    comma: usize,
    what: &str,
) -> Result<Vec<regex::Captures<'t>>, OwnedFileError> {
    let lines: Vec<&str> = region.split('\n').collect();
    let last = lines.len() - 1;
    let mut out = Vec::with_capacity(lines.len());
    for (i, l) in lines.into_iter().enumerate() {
        let caps = re.captures(l).ok_or_else(|| {
            OwnedFileError::Modified(format!("{what} {} is not one socket-patch writes", i + 1))
        })?;
        if caps[comma].is_empty() != (i == last) {
            return Err(OwnedFileError::Modified(format!(
                "{what} {} has a misplaced trailing comma",
                i + 1
            )));
        }
        out.push(caps);
    }
    Ok(out)
}

/// A `Modified` error.
fn modified(reason: impl Into<String>) -> OwnedFileError {
    OwnedFileError::Modified(reason.into())
}

/// The 1-based number of the first line where `text` and `fixed` differ.
fn first_differing_line(text: &str, fixed: &str) -> usize {
    text.split('\n')
        .zip(fixed.split('\n'))
        .take_while(|(a, b)| a == b)
        .count()
        + 1
}

/// Strict parse of a generated file of `mode`. The syntax line comes from
/// the installer the file carries.
///
/// - No socket-patch header (after an optional BOM) → [`OwnedFileError::Foreign`].
/// - Otherwise [`OwnedFileError::Modified`] unless: every fixed line is the
///   template's; every row and override matches its grammar with `,` on
///   all but the last; each pin has exactly a pom row then a jar row and one
///   override (in row order), with the same coordinates and uuid; the rels
///   are the coordinates' paths; hosted sources are `<index>/<rel>` under
///   one index naming the uuid, vendored sources `""`; every pin passes
///   [`validate_values`]; and the text re-renders byte-identically (modulo
///   CRLF), which also fixes the order and one pin per GA.
pub fn parse(mode: SbtFileMode, text: &str) -> Result<SbtOwnedFile, OwnedFileError> {
    let unbommed = text.trim_start_matches('\u{feff}');
    if !unbommed.starts_with(HEADER_PREFIX) {
        return Err(OwnedFileError::Foreign);
    }
    if unbommed.len() != text.len() {
        return Err(modified("the file starts with a byte-order mark"));
    }
    let crlf = text.contains("\r\n");
    let norm = text.replace("\r\n", "\n");
    if norm.contains('\r') {
        return Err(modified("the file has a stray carriage return"));
    }

    // The fixed text around the two regions; the head is shared by every line.
    let lines = [SbtLine::Sbt013, SbtLine::Sbt1, SbtLine::Sbt2];
    let tpl = template(mode, SbtLine::Sbt1);
    let (head, _) = tpl.split_once(ROWS).expect("template has rows");
    if !norm.starts_with(head) {
        return Err(modified(format!(
            "line {} is not socket-patch's",
            first_differing_line(&norm, head)
        )));
    }
    let mut found = None;
    for line in lines {
        let tpl = template(mode, line);
        let (_, rest) = tpl.split_once(ROWS).expect("template has rows");
        let (mid, tail) = rest.split_once(OVERRIDES).expect("template has overrides");
        let Some(body) = norm[head.len()..].strip_suffix(tail) else {
            continue;
        };
        if let Some((rows, overrides)) = body.split_once(mid) {
            found = Some((line, rows.to_string(), overrides.to_string()));
            break;
        }
    }
    let Some((line, rows_text, overrides_text)) = found else {
        return Err(modified(
            "the settings after the pin rows are not socket-patch's template",
        ));
    };
    if rows_text.is_empty() || overrides_text.is_empty() {
        return Err(modified("the file pins nothing"));
    }

    let rows: Vec<Row> = region_lines(&rows_text, &ROW, 7, "pin row")?
        .iter()
        .map(|c| Row {
            group: c.get(1).map_or("", |m| m.as_str()),
            artifact: c.get(2).map_or("", |m| m.as_str()),
            sv: c.get(3).map_or("", |m| m.as_str()),
            rel: c.get(4).map_or("", |m| m.as_str()),
            sha256: c.get(5).map_or("", |m| m.as_str()),
            src: c.get(6).map_or("", |m| m.as_str()),
            uuid: c.get(8).map_or("", |m| m.as_str()),
        })
        .collect();
    let overrides = region_lines(&overrides_text, &OVERRIDE, 4, "override")?;
    if !rows.len().is_multiple_of(2) {
        return Err(modified(
            "a pin does not have exactly a pom row and a jar row",
        ));
    }
    if rows.len() / 2 != overrides.len() {
        return Err(modified(
            "the overrides do not match the pin rows one to one",
        ));
    }

    let mut pins = BTreeMap::new();
    let mut seen = BTreeSet::new();
    for (pair, ov) in rows.chunks(2).zip(&overrides) {
        let (pom, jar) = (&pair[0], &pair[1]);
        let uuid = pom.uuid;
        let bad = |why: &str| modified(format!("pin {uuid}: {why}"));
        if !seen.insert(uuid) {
            return Err(bad("the uuid has more than two rows"));
        }
        if (jar.uuid, jar.group, jar.artifact, jar.sv) != (uuid, pom.group, pom.artifact, pom.sv) {
            return Err(bad("its pom and jar rows disagree"));
        }
        if (&ov[1], &ov[2], &ov[3], &ov[5]) != (pom.group, pom.artifact, pom.sv, uuid) {
            return Err(bad("its override does not match its rows"));
        }
        let mut index = None;
        for (row, ext) in [(pom, "pom"), (jar, "jar")] {
            if row.rel != layout::artifact_path(row.group, row.artifact, row.sv, None, ext) {
                return Err(bad(&format!("the {ext} path is not its coordinates' path")));
            }
            match mode {
                SbtFileMode::Vendored if !row.src.is_empty() => {
                    return Err(bad("a vendored row has a source URL"));
                }
                SbtFileMode::Vendored => {}
                SbtFileMode::Hosted => {
                    let Some(i) = row
                        .src
                        .strip_suffix(row.rel)
                        .and_then(|s| s.strip_suffix('/'))
                    else {
                        return Err(bad(&format!("the {ext} source URL is not under its path")));
                    };
                    if index.is_some_and(|prev| prev != i) {
                        return Err(bad("its pom and jar come from different indexes"));
                    }
                    index = Some(i);
                }
            }
        }
        let hex8 = crate::vendor::jvm::Coords {
            group_id: "",
            artifact_id: "",
            version: "",
            uuid,
        }
        .hex8();
        let Some(base) = pom.sv.strip_suffix(&format!("-socket.{hex8}")) else {
            return Err(bad("the version is not the uuid's suffixed version"));
        };
        let pin = SbtPin {
            uuid: uuid.to_string(),
            group: pom.group.to_string(),
            artifact: pom.artifact.to_string(),
            base: base.to_string(),
            sv: pom.sv.to_string(),
            pom_sha256: pom.sha256.to_string(),
            jar_sha256: jar.sha256.to_string(),
            deps_digest: ov[6].to_string(),
            index_url: index.map(str::to_string),
        };
        validate_values(&pin).map_err(&bad)?;
        check_mode(mode, &pin).map_err(bad)?;
        pins.insert(pin.uuid.clone(), pin);
    }

    let file = SbtOwnedFile {
        mode,
        line,
        crlf,
        pins,
    };
    match render(&SbtOwnedFile {
        crlf: false,
        ..file.clone()
    }) {
        Ok(again) if again == norm => Ok(file),
        Ok(_) => Err(modified("the pins are not in socket-patch's order")),
        Err(RenderError::Invalid { uuid, reason }) => {
            Err(modified(format!("pin {uuid}: {reason}")))
        }
        Err(RenderError::NoPins) => Err(modified("the file pins nothing")),
    }
}

/// `hash` as bare lowercase hex: a `sha256-` / `sha256:` prefix and
/// surrounding whitespace dropped (the patch API spells it several ways).
pub fn bare_sha256(hash: &str) -> String {
    crate::patch::redirect::bare_sha256_hex(hash)
}

/// The suffixed version for `base` and `uuid`: `<base>-socket.<hex8>`.
pub fn suffixed_version(base: &str, uuid: &str) -> String {
    crate::vendor::jvm::Coords {
        group_id: "",
        artifact_id: "",
        version: base,
        uuid,
    }
    .suffixed_version()
}

/// Whether every value of `p` is safe to write into the template's Scala
/// string literals and repository paths; the reason when not.
pub fn validate_values(p: &SbtPin) -> Result<(), &'static str> {
    static URL: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"^https?://[A-Za-z0-9._~:/%+-]+$").expect("regex"));
    if !crate::patch::path_safety::is_canonical_uuid(&p.uuid) {
        return Err("uuid is not a canonical uuid");
    }
    if !layout::safe_coordinates(&p.group, &p.artifact, &p.base) {
        return Err("unsafe maven coordinates");
    }
    if p.sv != suffixed_version(&p.base, &p.uuid) {
        return Err("suffixed version does not match the base and uuid");
    }
    if !layout::safe_coordinates(&p.group, &p.artifact, &p.sv) {
        return Err("unsafe suffixed version");
    }
    for hash in [&p.pom_sha256, &p.jar_sha256] {
        if !is_hex64_lower(&bare_sha256(hash)) {
            return Err("sha256 is not 64 hex digits");
        }
    }
    if p.deps_digest.len() != 8
        || !p
            .deps_digest
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
    {
        return Err("dependency digest is not 8 lowercase hex digits");
    }
    if let Some(url) = &p.index_url {
        if !URL.is_match(url) {
            return Err("index URL has characters outside the safe set");
        }
    }
    Ok(())
}

