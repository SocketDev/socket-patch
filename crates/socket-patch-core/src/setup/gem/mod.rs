    #[tokio::test]
    async fn test_stale_plugin_files_are_not_reported_as_configured() {
        // `setup --check`'s gem_plugin verdict must agree with what `setup`
        // itself would do. A plugin dir generated by an OLDER CLI is present but
        // stale, and a stale gemspec is not cosmetic: without the current
        // template's `s.require_paths = ["."]` Bundler refuses to load the
        // plugin ("The following plugin paths don't exist: .../lib ...
        // Continuing without installing plugin") and every `bundle install`
        // silently reverts the gem patches — while `--check` reported
        // "configured" and the CI gate went green.
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        write(&plugins_rb_path(root), PLUGINS_RB).await;
        // An older generated gemspec: carries our marker, but predates the
        // require_paths override.
        write(
            &gemspec_path(root),
            &format!(
                "{GENERATED_MARKER}\nGem::Specification.new do |s|\n  \
                 s.name = \"socket-patch\"\nend\n"
            ),
        )
        .await;

        assert!(
            !plugin_files_present(root).await,
            "a stale generated gemspec is not 'configured' — Bundler would not \
             load the plugin"
        );
        assert_eq!(
            add_plugin_files(root, true).await.status,
            GemSetupStatus::Updated,
            "check and setup must agree: setup would rewrite the stale file"
        );
    }

