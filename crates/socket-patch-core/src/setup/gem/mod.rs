/// The in-tree plugin directory, relative to the project root.
const PLUGIN_DIR: &str = ".socket/bundler-plugin";
/// First line of every generated plugin file — the ownership signal for removal
/// (we never delete a file that lacks it).
const GENERATED_MARKER: &str = "# Code generated by `socket-patch setup`. DO NOT EDIT.";
/// The generated plugin's digest stamp, relative to the project root
/// (machine-local state; the plugin owns its content, setup owns its lifecycle).
const STAMP_REL: &str = ".socket/gem-plugin-stamp";
/// The `.socket/.gitignore` line that keeps the stamp out of version control.
/// Everything else under `.socket/` is meant to be committed, so without this
/// line every install drops an untracked stamp into `git status` — and a stamp
/// committed by a blanket `git add .socket` ships one machine's digest to
/// every clone.
const STAMP_IGNORE_LINE: &str = "/gem-plugin-stamp";

/// The generated `plugins.rb` body (the two-trigger idempotent applier).
const PLUGINS_RB: &str = include_str!("templates/plugins.rb.tmpl");
/// The generated plugin gemspec.
const GEMSPEC: &str = include_str!("templates/gemspec.tmpl");

/// A discovered Bundler project.
#[derive(Debug, Clone)]
pub struct BundlerProject {
    /// Directory containing the Gemfile (the project root). The plugin dir and
    /// `.socket/manifest.json` live here.
    pub root: PathBuf,
    /// The Bundler manifest to edit (`Gemfile` or `gems.rb`).
    pub gemfile: PathBuf,
}

/// Find the Bundler project that `cwd` belongs to by walking up to the nearest
/// directory holding Bundler's alternate `gems.rb` or a `Gemfile` — exactly
/// how `bundle` itself resolves the manifest. The discovered
/// directory (not `cwd`) becomes the project `root`, so `.socket/` and the
/// plugin dir land next to the manifest even when `setup` is run from a
/// subdirectory. Returns `None` when no ancestor has one — a `Gemfile.lock`
/// alone is not editable, so it does not count.
///
/// The name order is Bundler's own: `Bundler::SharedHelpers.gemfile_names` is
/// `["gems.rb", "Gemfile"]`, and both names are tried in each directory before
/// ascending (`search_up`), so `gems.rb` only wins within a single directory —
/// a nearer `Gemfile` still beats a farther `gems.rb`. Getting this backwards
/// wires the `plugin` directive into the file `bundle` *ignores* (it even warns
/// "Multiple gemfiles (gems.rb and Gemfile) detected ... bundler is ignoring
/// them in favor of gems.rb and gems.locked"), so the plugin never loads and
/// every `bundle install` silently reverts the gem patches.
pub async fn discover_bundler_project(cwd: &Path) -> Option<BundlerProject> {
    let mut dir = cwd.to_path_buf();
    loop {
        for name in ["gems.rb", "Gemfile"] {
            let candidate = dir.join(name);
            if fs::metadata(&candidate).await.is_ok() {
                return Some(BundlerProject {
                    root: dir,
                    gemfile: candidate,
                });
            }
        }
        dir = if matches!(
            dir.components().next_back(),
            Some(std::path::Component::ParentDir)
        ) {
            // `Path::parent` is lexical: it strips a trailing `..`, stepping
            // the walk back DOWN into the directory the `..` just escaped
            // (parent of `a/b/..` is `a/b`) and probing descendants outside
            // the real ancestry. Resolve the position against the filesystem —
            // the same way the kernel resolved this iteration's metadata
            // probes — and continue from its real parent.
            fs::canonicalize(&dir).await.ok()?.parent()?.to_path_buf()
        } else {
            match dir.parent() {
                Some(parent) if !parent.as_os_str().is_empty() => parent.to_path_buf(),
                // A relative `cwd` (e.g. the CLI's default `--cwd .`) exhausts its
                // lexical components here (`Path::parent` of `.` is `Some("")`,
                // then `None`) without ever reaching the real parent directories.
                // Re-root the walk on the process cwd so the true ancestry is
                // still probed — `bundle` resolves the Gemfile from the invocation
                // dir's real ancestors, wherever it is run from.
                _ if dir.is_relative() => std::env::current_dir()
                    .ok()?
                    .join(&dir)
                    .parent()?
                    .to_path_buf(),
                _ => return None,
            }
        };
    }
}

/// Absolute path to the generated plugin directory for a project root.
pub fn plugin_dir(root: &Path) -> PathBuf {
    root.join(PLUGIN_DIR)
}

fn plugins_rb_path(root: &Path) -> PathBuf {
    plugin_dir(root).join("plugins.rb")
}

fn gemspec_path(root: &Path) -> PathBuf {
    plugin_dir(root).join("socket-patch.gemspec")
}

fn stamp_path(root: &Path) -> PathBuf {
    root.join(STAMP_REL)
}

fn stamp_gitignore_path(root: &Path) -> PathBuf {
    root.join(".socket").join(".gitignore")
}

/// Whether `.socket/.gitignore` is missing the stamp entry (so `setup` still
/// has a write to make). Shared by [`add_plugin_files`] and
/// [`plugin_files_present`] to keep `setup` and `--check` in agreement.
async fn stamp_ignore_missing(root: &Path) -> bool {
    match fs::read_to_string(stamp_gitignore_path(root)).await {
        Ok(c) => !c.lines().any(|l| l.trim() == STAMP_IGNORE_LINE),
        Err(_) => true,
    }
}

/// Append the stamp entry to `.socket/.gitignore`, preserving any existing
/// (user or other-tool) lines. Creates the file when absent.
async fn add_stamp_gitignore(root: &Path) -> Result<(), String> {
    let path = stamp_gitignore_path(root);
    let existing = fs::read_to_string(&path).await.unwrap_or_default();
    let mut body = existing;
    if !body.is_empty() && !body.ends_with('\n') {
        body.push('\n');
    }
    body.push_str(STAMP_IGNORE_LINE);
    body.push('\n');
    write_file(&path, &body).await
}

/// Best-effort cleanup of the stamp artifacts on `--remove`: delete the stamp
/// itself and strip our line from `.socket/.gitignore` (deleting the file when
/// nothing else is left, sparing any other lines). Best-effort by design — a
/// leftover stamp is inert machine-local state, not worth failing an
/// otherwise-successful unwire over.
async fn remove_stamp_artifacts(root: &Path) {
    let _ = fs::remove_file(stamp_path(root)).await;
    let path = stamp_gitignore_path(root);
    let Ok(content) = fs::read_to_string(&path).await else {
        return;
    };
    let kept: Vec<&str> = content
        .lines()
        .filter(|l| l.trim() != STAMP_IGNORE_LINE)
        .collect();
    if kept.len() == content.lines().count() {
        return;
    }
    if kept.iter().all(|l| l.trim().is_empty()) {
        let _ = fs::remove_file(&path).await;
    } else {
        let _ = fs::write(&path, format!("{}\n", kept.join("\n"))).await;
    }
}

// ─────────────────────────────────────────────────────────────────────────
// Bundler's machine-local plugin registration (`.bundle/plugin/index`)
// ─────────────────────────────────────────────────────────────────────────

/// The plugin name our Gemfile directive registers — the key/value bundler
/// records in its machine-local plugin index at first install.
const PLUGIN_NAME: &str = "socket-patch";

/// Outcome of clearing bundler's machine-local plugin registration on
/// `setup --remove`.
#[derive(Debug)]
pub enum GemRegistrationCleanup {
    /// socket-patch entries were found and removed (or would be, on dry-run).
    Cleaned {
        /// The registration index that held (or holds, on dry-run) them.
        index: PathBuf,
    },
    /// No socket-patch registration exists — nothing to clean.
    NotRegistered,
    /// A socket-patch registration is (probably) present but could not be
    /// cleared safely; the human remedy must be surfaced.
    Residue {
        /// The registration index carrying the leftover entries.
        index: PathBuf,
        /// Why the surgical cleanup refused/failed.
        reason: String,
    },
}

/// Bundler's app-config dir for `root`, following `Bundler.app_config_path`
/// exactly: `$BUNDLE_APP_CONFIG` when set (a relative value resolves against
/// the project root, NOT the process cwd), else `<root>/.bundle`. The
/// machine-local plugin registration lives at `<app config>/plugin/index`, so
/// getting this resolution wrong means `--remove` cleans (or misses) the
/// wrong directory — e.g. under the official ruby Docker images, which export
/// `BUNDLE_APP_CONFIG=/usr/local/bundle`.
fn bundler_app_config_dir(root: &Path, env_value: Option<&std::ffi::OsStr>) -> PathBuf {
    match env_value {
        Some(v) if !v.is_empty() => {
            let p = PathBuf::from(v);
            if p.is_absolute() {
                p
            } else {
                root.join(p)
            }
        }
        _ => root.join(".bundle"),
    }
}

/// One `key:` entry of a section in bundler's plugin index, carrying the raw
/// lines it spans so kept entries are rebuilt byte-verbatim.
struct IndexEntry {
    /// The entry key (unquoted): a plugin name, or a hook event name.
    key: String,
    key_line: String,
    /// Inline scalar value (`plugin_paths`-style `key: "value"`), unquoted.
    value: Option<String>,
    /// `- "item"` lines under the key, with their unquoted values.
    items: Vec<(String, String)>,
}

/// One top-level section (`commands` / `hooks` / `load_paths` /
/// `plugin_paths` / `sources`) of the index.
struct IndexSection {
    name: String,
    header_line: String,
    entries: Vec<IndexEntry>,
}

/// Strip a matching pair of quotes, mirroring bundler's `YAMLSerializer`
/// loader (its regexes accept an optional `'`/`"` wrapper around values).
fn unquote(s: &str) -> &str {
    let s = s.trim();
    let b = s.as_bytes();
    if s.len() >= 2 && ((b[0] == b'"' && b[s.len() - 1] == b'"') || (b[0] == b'\'' && b[s.len() - 1] == b'\'')) {
        &s[1..s.len() - 1]
    } else {
        s
    }
}

/// Parse bundler's plugin index into sections/entries, refusing anything
/// outside the exact dialect bundler's `YAMLSerializer` writes (`---`, then
/// two-level `key:` maps with 2-space indents and `- "item"` array lines).
/// The refusal matters more than the acceptance: a hand-edited or
/// future-format index must fall through to the "residue remains" remedy
/// path, never be rewritten on a guess and corrupted.
fn parse_plugin_index(content: &str) -> Result<Vec<IndexSection>, String> {
    let mut sections: Vec<IndexSection> = Vec::new();
    for (n, line) in content.lines().enumerate() {
        let lineno = n + 1;
        if n == 0 && line.trim_end() == "---" {
            continue;
        }
        if let Some(body) = line.strip_prefix("  ") {
            // Second level: an array item or an entry key.
            if body.starts_with(' ') || body.starts_with('\t') {
                return Err(format!("line {lineno}: unexpected indentation"));
            }
            let section = sections
                .last_mut()
                .ok_or_else(|| format!("line {lineno}: entry before any section"))?;
            if let Some(item) = body.strip_prefix("- ") {
                let entry = section
                    .entries
                    .last_mut()
                    .ok_or_else(|| format!("line {lineno}: array item before any key"))?;
                entry
                    .items
                    .push((line.to_string(), unquote(item).to_string()));
            } else if let Some((key, value)) = body.split_once(": ") {
                section.entries.push(IndexEntry {
                    key: unquote(key).to_string(),
                    key_line: line.to_string(),
                    value: Some(unquote(value).to_string()),
                    items: Vec::new(),
                });
            } else if let Some(key) = body.strip_suffix(':') {
                section.entries.push(IndexEntry {
                    key: unquote(key).to_string(),
                    key_line: line.to_string(),
                    value: None,
                    items: Vec::new(),
                });
            } else {
                return Err(format!("line {lineno}: unrecognized entry line"));
            }
        } else if let Some(name) = line.strip_suffix(':') {
            if name.is_empty() || name.contains(' ') || line.starts_with(' ') {
                return Err(format!("line {lineno}: unrecognized section line"));
            }
            sections.push(IndexSection {
                name: name.to_string(),
                header_line: line.to_string(),
                entries: Vec::new(),
            });
        } else {
            return Err(format!("line {lineno}: unrecognized line"));
        }
    }
    Ok(sections)
}

/// The result of surgically removing socket-patch from a parsed index.
struct StrippedIndex {
    /// The index content with every socket-patch entry removed; kept lines
    /// are byte-verbatim.
    content: String,
    /// Whether any OTHER plugin's registration remains (the index must then
    /// survive; an all-empty index is deleted instead).
    plugins_remain: bool,
    /// The dir bundler recorded as the plugin's install location
    /// (`plugin_paths`), if present.
    installed_dir: Option<PathBuf>,
}

/// Pure transform: drop every socket-patch entry from the index — its
/// `plugin_paths`/`load_paths` keys, its `hooks` subscriptions (removing an
/// event key left with no subscribers), and any `commands`/`sources` mapping
/// to it — while preserving every other plugin's lines byte-verbatim.
/// `Ok(None)` when nothing of ours is registered; `Err` when the file is not
/// in bundler's dialect (the caller must warn, never write).
fn strip_plugin_registration(content: &str) -> Result<Option<StrippedIndex>, String> {
    let mut sections = parse_plugin_index(content)?;
    let mut changed = false;
    let mut installed_dir = None;
    for section in &mut sections {
        match section.name.as_str() {
            "plugin_paths" | "load_paths" => {
                let is_plugin_paths = section.name == "plugin_paths";
                section.entries.retain(|e| {
                    if e.key != PLUGIN_NAME {
                        return true;
                    }
                    if is_plugin_paths {
                        if let Some(v) = &e.value {
                            installed_dir = Some(PathBuf::from(v));
                        }
                    }
                    changed = true;
                    false
                });
            }
            "hooks" => {
                section.entries.retain_mut(|e| {
                    let before = e.items.len();
                    e.items.retain(|(_, v)| v != PLUGIN_NAME);
                    let lost = e.items.len() != before;
                    changed |= lost;
                    // Drop an event key we just emptied — bundler never
                    // writes a subscriber-less event, so leaving one behind
                    // is not round-trippable. Entries empty on arrival are
                    // not ours to judge and stay.
                    !(lost && e.items.is_empty() && e.value.is_none())
                });
            }
            "commands" | "sources" => {
                section.entries.retain(|e| {
                    if e.value.as_deref() == Some(PLUGIN_NAME) {
                        changed = true;
                        false
                    } else {
                        true
                    }
                });
            }
            // Unknown section (a future bundler's addition): keep verbatim.
            _ => {}
        }
    }
    if !changed {
        return Ok(None);
    }
    let plugins_remain = sections.iter().any(|s| !s.entries.is_empty());
    let mut out = String::from("---\n");
    for section in &sections {
        out.push_str(&section.header_line);
        out.push('\n');
        for entry in &section.entries {
            out.push_str(&entry.key_line);
            out.push('\n');
            for (line, _) in &entry.items {
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    Ok(Some(StrippedIndex {
        content: out,
        plugins_remain,
        installed_dir,
    }))
}

/// Clear bundler's machine-local plugin registration for socket-patch on
/// `setup --remove` — the `.bundle/plugin/index` entries (hook subscriptions
/// and plugin/load paths) bundler wrote when the wired plugin first installed.
/// `remove_plugin_files` deletes the plugin *source*; without this step the
/// registration dangles and every later `bundle install` prints bundler's
/// "The following plugin paths don't exist ... Continuing without installing
/// plugin socket-patch" block (with a misleading reinstall suggestion)
/// forever. Surgical: only socket-patch entries leave the index; another
/// plugin's registration survives byte-verbatim, and an index in an
/// unexpected format is never rewritten on a guess — that reports
/// [`GemRegistrationCleanup::Residue`] so the caller surfaces the
/// `bundler plugin uninstall socket-patch` remedy instead.
pub async fn remove_plugin_registration(root: &Path, dry_run: bool) -> GemRegistrationCleanup {
    let env = std::env::var_os("BUNDLE_APP_CONFIG");
    remove_plugin_registration_at(root, env.as_deref(), dry_run).await
}

/// [`remove_plugin_registration`] with the `BUNDLE_APP_CONFIG` resolution
/// input made explicit (tests inject it; the public entry reads the process
/// env, exactly like bundler itself).
async fn remove_plugin_registration_at(
    root: &Path,
    app_config_env: Option<&std::ffi::OsStr>,
    dry_run: bool,
) -> GemRegistrationCleanup {
    let plugin_root = bundler_app_config_dir(root, app_config_env).join("plugin");
    let index = plugin_root.join("index");
    let content = match fs::read_to_string(&index).await {
        Ok(c) => c,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return GemRegistrationCleanup::NotRegistered;
        }
        Err(e) => {
            return GemRegistrationCleanup::Residue {
                index,
                reason: format!("could not read it: {e}"),
            };
        }
    };
    if !content.contains(PLUGIN_NAME) {
        return GemRegistrationCleanup::NotRegistered;
    }
    let stripped = match strip_plugin_registration(&content) {
        Ok(Some(s)) => s,
        // Mentioned only incidentally (e.g. inside another plugin's path):
        // nothing registered under our name.
        Ok(None) => return GemRegistrationCleanup::NotRegistered,
        Err(reason) => {
            return GemRegistrationCleanup::Residue {
                index,
                reason: format!("unexpected index format ({reason})"),
            };
        }
    };
    if dry_run {
        return GemRegistrationCleanup::Cleaned { index };
    }
    // The dir bundler recorded as the plugin's install location. For our
    // `path:`-sourced wiring that is the project's `.socket/bundler-plugin`
    // (already deleted by `remove_plugin_files`); a `bundler plugin install`ed
    // copy lives under the plugin root itself. Delete it only inside that
    // root — never a recorded path elsewhere on the machine. The recorded
    // path is attacker-authored input (the index can be committed), and
    // `starts_with` compares components lexically, so a `..` traversal like
    // `<plugin_root>/../../victim` would pass the prefix check while pointing
    // anywhere on the machine: reject any `..` component outright (bundler
    // never records traversal paths, so nothing legitimate is lost).
    if let Some(dir) = &stripped.installed_dir {
        let traversal_free = dir
            .components()
            .all(|c| !matches!(c, std::path::Component::ParentDir));
        if traversal_free && dir.starts_with(&plugin_root) && dir != &plugin_root {
            let _ = fs::remove_dir_all(dir).await;
        }
    }
    let write_result = if stripped.plugins_remain {
        // Another plugin is still registered: rewrite the index without our
        // entries (staged + renamed — a torn index would break EVERY plugin).
        crate::utils::fs::atomic_write_bytes_preserving_mode(&index, stripped.content.as_bytes())
            .await
            .map_err(|e| format!("could not rewrite it: {e}"))
    } else {
        // Nothing registered anymore: delete the index outright (bundler
        // treats a missing index as empty and regenerates it on demand).
        match fs::remove_file(&index).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(format!("could not delete it: {e}")),
        }
    };
    if let Err(reason) = write_result {
        return GemRegistrationCleanup::Residue { index, reason };
    }
    if !stripped.plugins_remain {
        // Prune the now-empty machine-local plugin dir (and an app-config dir
        // that held nothing else). `remove_dir` refuses non-empty dirs, so a
        // `.bundle/config` or another plugin's `gems/` cache keeps its parent.
        let _ = fs::remove_dir(&plugin_root).await;
        if let Some(parent) = plugin_root.parent() {
            let _ = fs::remove_dir(parent).await;
        }
    }
    GemRegistrationCleanup::Cleaned { index }
}

/// Whether the generated plugin files are present *and* match the templates the
/// current CLI generates (the `setup --check` "configured" signal, paired with
/// the Gemfile directive check).
///
/// Mere presence is not enough. A plugin dir generated by an older CLI is on
/// disk but stale, and stale content is not cosmetic: a gemspec predating
/// `s.require_paths = ["."]` makes Bundler refuse to load the plugin ("The
/// following plugin paths don't exist: .../lib ... Continuing without installing
/// plugin"), so `bundle install` silently reverts the gem patches while
/// `--check` reported "configured" and the CI gate went green. Keying on the
/// same [`needs_write`] predicate [`add_plugin_files`] uses keeps the two in
/// agreement: whenever `setup` would rewrite a file, `--check` says
/// needs-configuration.
pub async fn plugin_files_present(root: &Path) -> bool {
    !needs_write(&plugins_rb_path(root), PLUGINS_RB).await
        && !needs_write(&gemspec_path(root), GEMSPEC).await
        && !stamp_ignore_missing(root).await
}

/// True if the file is absent or its content differs from `desired`.
async fn needs_write(path: &Path, desired: &str) -> bool {
    match fs::read_to_string(path).await {
        Ok(c) => c != desired,
        Err(_) => true,
    }
}

async fn write_file(path: &Path, body: &str) -> Result<(), String> {
    if let Some(p) = path.parent() {
        fs::create_dir_all(p)
            .await
            .map_err(|e| format!("create {}: {e}", p.display()))?;
    }
    fs::write(path, body)
        .await
        .map_err(|e| format!("write {}: {e}", path.display()))
}

/// Generate `.socket/bundler-plugin/{plugins.rb, socket-patch.gemspec}` and
/// make sure `.socket/.gitignore` keeps the plugin's digest stamp untracked.
/// Idempotent: `AlreadyConfigured` when everything already matches. `kind =
/// "gem_plugin"`.
async fn add_plugin_files(root: &Path, dry_run: bool) -> GemEditResult {
    let dir = plugin_dir(root);
    let result = async {
        let rb_changed = needs_write(&plugins_rb_path(root), PLUGINS_RB).await;
        let spec_changed = needs_write(&gemspec_path(root), GEMSPEC).await;
        let ignore_missing = stamp_ignore_missing(root).await;
        if !rb_changed && !spec_changed && !ignore_missing {
            return Ok(false);
        }
        if !dry_run {
            if rb_changed {
                write_file(&plugins_rb_path(root), PLUGINS_RB).await?;
            }
            if spec_changed {
                write_file(&gemspec_path(root), GEMSPEC).await?;
            }
            if ignore_missing {
                add_stamp_gitignore(root).await?;
            }
        }
        Ok(true)
    }
    .await;
    GemEditResult::from_result("gem_plugin", dir.display().to_string(), result)
}

/// Whether the file at `path` carries our [`GENERATED_MARKER`] as its first
/// line — the per-file ownership test for removal.
async fn is_generated(path: &Path) -> bool {
    match fs::read_to_string(path).await {
        Ok(content) => content.starts_with(GENERATED_MARKER),
        Err(_) => false,
    }
}

/// Delete a generated file, tolerating it already being gone but surfacing
/// any other failure (a swallowed error here would report a false "removed").
async fn remove_generated(path: &Path) -> Result<(), String> {
    match fs::remove_file(path).await {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(format!("remove {}: {e}", path.display())),
    }
}

/// Remove the generated plugin files — each only when it carries our
/// [`GENERATED_MARKER`], so a user-authored file at either path is never
/// deleted (and an orphaned generated file is still cleaned up) — plus the
/// plugin's digest stamp and its `.socket/.gitignore` entry (the plugin that
/// maintained them is being unwired; leaving the stamp behind would orphan it
/// in the otherwise-committed `.socket/`). Idempotent: `AlreadyConfigured`
/// when nothing of ours is there.
async fn remove_plugin_files(root: &Path, dry_run: bool) -> GemEditResult {
    let dir = plugin_dir(root);
    let result = async {
        let rb_ours = is_generated(&plugins_rb_path(root)).await;
        let spec_ours = is_generated(&gemspec_path(root)).await;
        if !rb_ours && !spec_ours {
            return Ok(false);
        }
        if !dry_run {
            if rb_ours {
                remove_generated(&plugins_rb_path(root)).await?;
            }
            if spec_ours {
                remove_generated(&gemspec_path(root)).await?;
            }
            remove_stamp_artifacts(root).await;
            // Prune the now-empty plugin dir (leave .socket/ — apply uses it).
            let _ = fs::remove_dir(&dir).await;
        }
        Ok(true)
    }
    .await;
    GemEditResult::from_result("gem_plugin", dir.display().to_string(), result)
}

