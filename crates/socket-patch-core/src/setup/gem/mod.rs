    #[test]
    fn test_plugin_template_failure_policy_and_stamp_location() {
        // Failure policy: tolerant by default — a patch failure WARNS (with
        // the manual-apply remediation) and lets `bundle install` continue.
        // Bundler evaluates plugins.rb at plugin REGISTRATION, before any
        // project gem is installed; a raise there deadlocks a fresh clone on
        // its own first `bundle install` (plugin registration fails, every
        // retry fails identically — reproduced against bundler 2.7 and 4.0).
        assert!(
            PLUGINS_RB.contains("def report_failure"),
            "the applier must route failures through the tolerant reporter"
        );
        assert!(
            !PLUGINS_RB.contains("def fail!"),
            "the unconditional raise helper must be gone — it is what \
             deadlocked bootstrap installs"
        );
        assert!(
            PLUGINS_RB.contains("warn(message)"),
            "tolerant mode must surface the failure as a stderr warning"
        );
        assert!(
            PLUGINS_RB.contains("socket-patch apply --ecosystems gem"),
            "the warning must name the manual remediation command"
        );
        // Strict escape hatch: SOCKET_PATCH_STRICT=1 restores raise-on-failure.
        assert!(PLUGINS_RB.contains("SOCKET_PATCH_STRICT"));
        assert!(
            PLUGINS_RB.contains("BundlerError"),
            "strict mode must still raise Bundler::BundlerError"
        );
        // The strict raise must carry a strict trailer, not the tolerant
        // "`bundle install` continues" text (which is false mid-raise).
        assert!(PLUGINS_RB.contains("def failure_trailer"));
        // Stamp location: project-scoped under .socket/, NOT a fixed-name file
        // in Bundler.bundle_path (machine-global with no bundle path
        // configured, shared and clobbered across every project on the host).
        assert!(PLUGINS_RB.contains("STAMP_NAME = \"gem-plugin-stamp\""));
        assert!(PLUGINS_RB.contains("File.join(socket_dir, STAMP_NAME)"));
        // The legacy global stamp is cleaned up, never read.
        assert!(PLUGINS_RB.contains("LEGACY_STAMP_NAME = \".socket-patch-gem-stamp\""));
        assert!(PLUGINS_RB.contains("def remove_legacy_stamp"));
        // The stamp must be excluded from its own digest inputs, or every
        // write would invalidate the digest it records.
        assert!(PLUGINS_RB.contains("p != stamp_path"));
        // The bootstrap gate keys on the patch targets existing on disk, NEVER
        // on the stamp: `.socket/` is a committed directory, so a stale stamp
        // that reaches version control would otherwise pass the gate at plugin
        // REGISTRATION on a fresh clone and resurrect the strict-mode
        // bootstrap deadlock this plugin exists to avoid.
        assert!(PLUGINS_RB.contains("bootstrap_gate && patch_target_files.none?"));
        assert!(
            !PLUGINS_RB.contains("require_stamp"),
            "the stamp-existence gate must be gone — a committed stamp made it \
             a remote-controlled registration deadlock"
        );

        // The published-gem twin must carry the same applier contract.
        let published = include_str!("../../../../../gem/socket-patch-bundler/plugins.rb");
        for needle in [
            "def report_failure",
            "def failure_trailer",
            "SOCKET_PATCH_STRICT",
            "STAMP_NAME = \"gem-plugin-stamp\"",
            "def remove_legacy_stamp",
            "def patch_target_files",
            r#"glob_gems_dir = gems_dir.tr("\\", "/")"#,
            "bootstrap_gate && patch_target_files.none?",
            "Bundler::Plugin.add_hook(\"after-install\")",
            "Bundler::Plugin.add_hook(\"after-install-all\")",
        ] {
            assert!(
                published.contains(needle),
                "published plugins.rb drifted from the template: missing {needle:?}"
            );
        }
        assert!(!published.contains("def fail!"));
        assert!(!published.contains("require_stamp"));
    }

    #[tokio::test]
    async fn test_add_then_remove_plugin_files_roundtrip() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        let r = add_plugin_files(root, false).await;
        assert_eq!(r.status, GemSetupStatus::Updated);
        assert!(plugin_files_present(root).await);
        assert_eq!(
            fs::read_to_string(plugins_rb_path(root)).await.unwrap(),
            PLUGINS_RB
        );
        // The stamp is gitignored: everything else under .socket/ is committed,
        // so without this line every install litters `git status` and a blanket
        // `git add .socket` commits one machine's stamp to every clone.
        assert_eq!(
            fs::read_to_string(stamp_gitignore_path(root))
                .await
                .unwrap(),
            "/gem-plugin-stamp\n"
        );
        // Idempotent.
        assert_eq!(
            add_plugin_files(root, false).await.status,
            GemSetupStatus::AlreadyConfigured
        );
        // Remove — including the stamp a previous apply left behind, which
        // would otherwise be orphaned in the committed .socket/ dir.
        fs::write(stamp_path(root), "f".repeat(64)).await.unwrap();
        let rr = remove_plugin_files(root, false).await;
        assert_eq!(rr.status, GemSetupStatus::Updated);
        assert!(!plugin_files_present(root).await);
        assert!(!plugin_dir(root).exists(), "empty plugin dir pruned");
        assert!(!stamp_path(root).exists(), "stamp removed with the plugin");
        assert!(
            !stamp_gitignore_path(root).exists(),
            "the .gitignore we created (nothing but our line) is removed too"
        );
        // Remove again → already gone.
        assert_eq!(
            remove_plugin_files(root, false).await.status,
            GemSetupStatus::AlreadyConfigured
        );
    }

