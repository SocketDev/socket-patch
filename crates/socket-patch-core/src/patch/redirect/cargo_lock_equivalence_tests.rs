//! Seeded and hand-written Cargo.lock sweeps for the hosted splice, which
//! edits the byte spans of the lock's one parse ([`CargoLock::parse`] →
//! [`CargoLock::plan_hosted_splices`]). Every plan is pinned per case by
//! `tests/equivalence/cargo_lock_*.golden`, blessed while the previous
//! line-grammar planner still ran beside it as an oracle (identical bytes
//! and edits wherever that grammar could read the lock).

use crate::formats::cargo::hosted::{splice, CargoHostedLock, CargoLockOutcome, RepointSplices};
use crate::formats::cargo::CargoLock;
use crate::golden::Golden;
use crate::patch::redirect::FileEdit;
use crate::test_rng::Rng;

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// A lock in the given format: v1 (checksums in a trailing `[metadata]`,
/// full-id dependency references), or v3/v4 (inline checksums). Randomly
/// sprinkles the hostile shapes the bound must not be fooled by: marker
/// look-alikes inside strings, multi-byte names, blank-line runs between
/// blocks, `[[patch.unused]]` / `[patch.*]` trailers, and a missing final
/// newline.
fn synth_lock(rng: &mut Rng, blocks: usize, v1: bool) -> String {
    let mut out = String::new();
    out.push_str("# This file is automatically @generated by Cargo.\n");
    out.push_str("# It is not intended for manual editing.\n");
    if !v1 {
        out.push_str(if rng.chance(50) {
            "version = 4\n"
        } else {
            "version = 3\n"
        });
    }
    let mut metadata = Vec::new();
    for i in 0..blocks {
        out.push('\n');
        if rng.chance(10) {
            out.push('\n');
        }
        let name = match rng.below(5) {
            0 => format!("crate-é{i}"),
            1 => format!("crate_{i}"),
            _ => format!("c{i}"),
        };
        let version = format!("{}.{}.{}", rng.below(3), rng.below(20), rng.below(9));
        out.push_str(&format!(
            "[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n"
        ));
        let has_source = !rng.chance(15);
        if has_source {
            out.push_str(&format!("source = \"{CRATES_IO}\"\n"));
            let sum = format!("{:016x}{:016x}", rng.next(), rng.next());
            if v1 {
                metadata.push(format!(
                    "\"checksum {name} {version} ({CRATES_IO})\" = \"{sum}\""
                ));
            } else {
                out.push_str(&format!("checksum = \"{sum}\"\n"));
            }
        }
        if rng.chance(70) {
            out.push_str("dependencies = [\n");
            for d in 0..rng.below(5) {
                let dep = format!("c{}", (i + d + 1) % blocks.max(1));
                if v1 || rng.chance(20) {
                    out.push_str(&format!(" \"{dep} 0.1.0 ({CRATES_IO})\",\n"));
                } else {
                    out.push_str(&format!(" \"{dep}\",\n"));
                }
            }
            if rng.chance(10) {
                // Marker look-alikes that are NOT line-anchored.
                out.push_str(" \"x [metadata] [[package]] [patch.unused]\",\n");
            }
            out.push_str("]\n");
        }
    }
    if (v1 || rng.chance(20)) && (!metadata.is_empty() || rng.chance(50)) {
        out.push_str("\n[metadata]\n");
        for line in &metadata {
            out.push_str(line);
            out.push('\n');
        }
    }
    if rng.chance(30) {
        out.push_str("\n[[patch.unused]]\nname = \"unused\"\nversion = \"1.0.0\"\n");
    }
    if rng.chance(15) {
        out.push_str("\n[patch.crates-io]\n");
    }
    if rng.chance(20) {
        while out.ends_with('\n') {
            out.pop();
        }
    } else if rng.chance(20) {
        out.push_str("\n\n");
    }
    out
}

const INDEX: &str = "sparse+https://socket.example/cargo/index/";
const OTHER_INDEX: &str = "sparse+https://socket.example/cargo/other-index/";

/// A lock whose full ids name packages it holds, which [`synth_lock`]
/// almost never does (its references are all at version `0.1.0`). Each
/// package depends on a few others in the spellings cargo writes. Some
/// are at a hosted index already (a re-run), some are twins of the package
/// before them from another source, and now and then a reference or a
/// `[metadata]` line names an id no block has (a lock edited by hand, which
/// a repoint can turn into one that no longer parses). The v1 shape has a
/// `[root]` and keeps its checksums in `[metadata]`.
fn linked_lock(rng: &mut Rng, blocks: usize, v1: bool) -> String {
    let sources = [CRATES_IO, INDEX, OTHER_INDEX];
    let mut packages: Vec<(String, String, Option<&str>)> = Vec::new();
    for i in 0..blocks {
        let source = match rng.below(20) {
            0..=13 => Some(CRATES_IO),
            14..=15 => Some(INDEX),
            16 => Some(OTHER_INDEX),
            _ => None,
        };
        let twin = packages
            .last()
            .filter(|(_, _, of)| *of != source && rng.chance(12));
        let (name, version) = match twin {
            Some((name, version, _)) => (name.clone(), version.clone()),
            None => (format!("c{i}"), format!("1.{}.0", rng.below(3))),
        };
        packages.push((name, version, source));
    }
    let full_id = |name: &str, version: &str, source: &str| format!("{name} {version} ({source})");
    let reference = |rng: &mut Rng, at: usize| -> String {
        let (name, version, source) = &packages[at];
        if rng.chance(8) {
            // No block has this id: another source than the package's.
            return full_id(name, version, sources[rng.below(sources.len())]);
        }
        match source {
            Some(source) if v1 || rng.chance(25) => full_id(name, version, source),
            _ if rng.chance(30) => format!("{name} {version}"),
            _ => name.clone(),
        }
    };
    let mut out = String::from("# This file is automatically @generated by Cargo.\n");
    if !v1 {
        out.push_str("version = 4\n");
    } else if !packages.is_empty() && rng.chance(40) {
        out.push_str("[root]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n");
        for _ in 0..1 + rng.below(3) {
            let at = rng.below(packages.len());
            out.push_str(&format!(" \"{}\",\n", reference(rng, at)));
        }
        out.push_str("]\n");
    }
    let mut metadata: Vec<String> = Vec::new();
    for (i, (name, version, source)) in packages.iter().enumerate() {
        out.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n"
        ));
        if let Some(source) = source {
            out.push_str(&format!("source = \"{source}\"\n"));
            let sum = format!("{:016x}", rng.next());
            if v1 {
                let key = format!("checksum {}", full_id(name, version, source));
                if !metadata
                    .iter()
                    .any(|line| line.starts_with(&format!("\"{key}\"")))
                {
                    metadata.push(format!("\"{key}\" = \"{sum}\""));
                }
            } else {
                out.push_str(&format!("checksum = \"{sum}\"\n"));
            }
        }
        let count = rng.below(4);
        if count > 0 && packages.len() > 1 {
            out.push_str("dependencies = [\n");
            for _ in 0..count {
                let at = (i + 1 + rng.below(packages.len() - 1)) % packages.len();
                out.push_str(&format!(" \"{}\",\n", reference(rng, at)));
            }
            out.push_str("]\n");
        }
    }
    if v1 {
        // A line for an id no block has, at the index a repoint may name.
        for (name, version, source) in &packages {
            if *source == Some(CRATES_IO) && rng.chance(6) {
                let key = format!("checksum {}", full_id(name, version, INDEX));
                if !metadata
                    .iter()
                    .any(|line| line.starts_with(&format!("\"{key}\"")))
                {
                    metadata.push(format!("\"{key}\" = \"stale\""));
                }
            }
        }
        out.push_str("\n[metadata]\n");
        for line in &metadata {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// A plan as comparable data: what it is, the text it leaves, the edits
/// it records.
type Shape = (String, Option<String>, Vec<FileEdit>);

/// One package of `lock` planned for `index` on a fresh parse of it.
fn plan_on(lock: &str, name: &str, version: &str, index: &str, cksum: &str) -> Shape {
    let Ok(model) = CargoLock::parse(lock) else {
        return ("not-found".into(), None, Vec::new());
    };
    match model.plan_hosted_splices(lock, name, version, index, cksum) {
        CargoLockOutcome::Rewritten(RepointSplices { splices, edits, .. }) => {
            ("rewritten".into(), Some(splice(lock, splices)), edits)
        }
        CargoLockOutcome::AlreadyRedirected => ("already".into(), None, Vec::new()),
        CargoLockOutcome::NotFound => ("not-found".into(), None, Vec::new()),
        CargoLockOutcome::Ambiguous => ("ambiguous".into(), None, Vec::new()),
    }
}

fn check(g: &mut Golden, lock: &str, name: &str, version: &str, cksum: &str) -> Option<String> {
    assert!(CargoLock::parse(lock).is_ok(), "synthesized locks parse");
    let new = plan_on(lock, name, version, INDEX, cksum);
    g.next(&(lock, name, version, cksum), &new);
    new.1
}

/// `(name, version)` of every `[[package]]` the lock holds, in order.
fn targets(lock: &str) -> Vec<(String, String)> {
    CargoLock::parse(lock)
        .expect("synthesized locks parse")
        .packages()
        .iter()
        .map(|p| (p.name.clone(), p.version.clone()))
        .collect()
}

/// Every package of `lock`, then a second package planned over the first's
/// output and a re-run of the first (the no-op path), and an absent package.
fn sweep_lock(g: &mut Golden, lock: &str, rng: &mut Rng) {
    let all = targets(lock);
    for (name, version) in &all {
        let cksum = format!("{:016x}{:016x}", rng.next(), rng.next());
        let Some(once) = check(g, lock, name, version, &cksum) else {
            continue;
        };
        check(g, &once, name, version, &cksum);
        if let Some((other, other_version)) = all.get(rng.below(all.len())) {
            check(g, &once, other, other_version, "00ff");
        }
    }
    check(g, lock, "absent-crate", "9.9.9", "00");
}

#[test]
fn span_splice_matches_golden_on_random_locks() {
    let mut g = Golden::new(
        "cargo_lock_random",
        "One package of a seeded Cargo.lock, planned for the hosted index.",
    )
    .chunked(20);
    let mut rng = Rng(0x9E37_79B9_7F4A_7C15);
    for _ in 0..300 {
        let v1 = rng.chance(50);
        let blocks = rng.below(12);
        let lock = synth_lock(&mut rng, blocks, v1);
        sweep_lock(&mut g, &lock, &mut rng);
    }
    g.finish();
}

/// Hand-written shapes the generator does not produce: multi-source twins
/// (one at the target index, and none), a v1 `[root]` table, a v1 block with
/// no source, a source ending the text, and blocks with neither line.
fn hand_written_locks() -> Vec<String> {
    let crates_io = CRATES_IO;
    let twins_ours = format!(
        "version = 3\n\n[[package]]\nname = \"t\"\nversion = \"1.0.0\"\nsource = \"{crates_io}\"\nchecksum = \"aa\"\n\n[[package]]\nname = \"t\"\nversion = \"1.0.0\"\nsource = \"{INDEX}\"\nchecksum = \"bb\"\n"
    );
    let twins_neither = twins_ours.replace(INDEX, "registry+https://other.example/index");
    let v1_root = format!(
        "[root]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"d 1.0.0 ({crates_io})\",\n]\n\n[[package]]\nname = \"d\"\nversion = \"1.0.0\"\nsource = \"{crates_io}\"\n\n[[package]]\nname = \"u\"\nversion = \"2.0.0\"\nsource = \"{crates_io}\"\ndependencies = [\n \"d 1.0.0 ({crates_io})\",\n]\n\n[metadata]\n\"checksum d 1.0.0 ({crates_io})\" = \"cc\"\n\"checksum u 2.0.0 ({crates_io})\" = \"dd\"\n"
    );
    let sourceless_v1 = "[[package]]\nname = \"s\"\nversion = \"1.0.0\"\n\n[metadata]\n\"checksum s 1.0.0 (registry+x)\" = \"ee\"\n".to_string();
    let source_at_eof =
        format!("[[package]]\nname = \"e\"\nversion = \"1.0.0\"\nsource = \"{crates_io}\"");
    let bare = "version = 3\n\n[[package]]\nname = \"b\"\nversion = \"1.0.0\"\n\n[[package]]\nname = \"c\"\nversion = \"1.0.0\"\n".to_string();
    vec![
        twins_ours,
        twins_neither,
        v1_root,
        sourceless_v1,
        source_at_eof,
        bare,
    ]
}

