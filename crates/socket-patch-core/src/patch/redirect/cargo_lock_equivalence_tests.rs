/// One step of a rewrite: a package, the index it is repointed at, the
/// patched checksum, and whether the plan is committed or dropped.
type Step = (String, String, &'static str, String, bool);

/// Repoint a run of `steps` packages of `lock` twice over: crate by crate,
/// each planned on a fresh parse of the text the last one left (the
/// rewrite as it was), and through one [`CargoHostedLock`]. Every plan,
/// every answer the rewrite's probes read, and the final text must be the
/// same. Returns how often the [`CargoHostedLock`] parsed.
fn repoint_both_ways(lock: &str, steps: &[Step]) -> usize {
    let mut text = lock.to_string();
    let mut held = CargoHostedLock::new(lock.to_string());
    for (at, (name, version, index, cksum, commit)) in steps.iter().enumerate() {
        let context = || format!("step {at} ({name}@{version} to {index}) of {steps:?}\n{lock}");
        // What the probes read, before the plan: the package's source and
        // the source of each package that depends on it.
        let probes = |model: Option<&CargoLock>| {
            model.map(|model| {
                let own: Vec<Option<String>> = model
                    .packages()
                    .iter()
                    .filter(|p| p.name == *name && p.version == *version)
                    .map(|p| p.source.clone())
                    .collect();
                let dependents: Vec<(String, String, Option<String>)> = model
                    .dependents(name, version)
                    .map(|p| (p.name.clone(), p.version.clone(), p.source.clone()))
                    .collect();
                (
                    own,
                    dependents,
                    model.is_locked(name, version),
                    model.locked_versions(name),
                )
            })
        };
        let fresh = CargoLock::parse(&text).ok();
        assert_eq!(
            probes(held.model()),
            probes(fresh.as_ref()),
            "{}",
            context()
        );

        let (kind, content, edits) = plan_on(&text, name, version, index, cksum);
        let (got, planned) = match held.plan(name, version, index, cksum) {
            CargoLockOutcome::Rewritten(planned) => ("rewritten", Some(planned)),
            CargoLockOutcome::AlreadyRedirected => ("already", None),
            CargoLockOutcome::NotFound => ("not-found", None),
            CargoLockOutcome::Ambiguous => ("ambiguous", None),
        };
        assert_eq!(got, kind.as_str(), "{}", context());
        let planned_edits = planned.as_ref().map_or(&[][..], |planned| planned.edits());
        assert_eq!(planned_edits, edits.as_slice(), "{}", context());
        if *commit {
            if let Some(content) = content {
                text = content;
            }
            if let Some(planned) = planned {
                assert_eq!(held.commit(planned), edits, "{}", context());
            }
        }
    }
    let parses = held.parses();
    assert_eq!(held.into_text(), text, "{steps:?}\n{lock}");
    parses
}

/// A run of repoints over `lock`: its packages in a seeded order with
/// repeats, an absent one, two target indexes (a package repointed to one
/// and then the other is a re-pin) and now and then a plan that is dropped.
fn seeded_steps(lock: &str, rng: &mut Rng) -> Vec<Step> {
    let all = targets(lock);
    (0..1 + rng.below(8))
        .map(|_| {
            let (name, version) = match all.get(rng.below(all.len() + 1)) {
                Some(found) => found.clone(),
                None => ("absent-crate".to_string(), "9.9.9".to_string()),
            };
            let index = if rng.chance(75) { INDEX } else { OTHER_INDEX };
            let cksum = format!("{:016x}", rng.next());
            (name, version, index, cksum, !rng.chance(10))
        })
        .collect()
}

/// The rewrite keeps one parse of a lock and its repoints as splices into
/// that text. Its plans, what its probes read and its final text are those
/// of the crate-by-crate rewrite it replaces, for every order and overlap:
/// a package repointed again, a block holding a full id an earlier repoint
/// rewrites, twins, a block that had no source, a lock ending without a
/// newline, a lock a repoint leaves unreadable.
#[test]
fn a_rewrite_on_one_parse_matches_the_crate_by_crate_rewrite() {
    let mut rng = Rng(0x6A09_E667_F3BC_C908);
    for _ in 0..600 {
        let v1 = rng.chance(50);
        let blocks = rng.below(12);
        let lock = synth_lock(&mut rng, blocks, v1);
        let steps = seeded_steps(&lock, &mut rng);
        repoint_both_ways(&lock, &steps);
    }
    // Full ids that name the lock's own packages: the references a repoint
    // rewrites in other blocks, in `[root]` and in `[metadata]`.
    let mut references = 0;
    for _ in 0..1_500 {
        let v1 = rng.chance(50);
        let blocks = rng.below(10);
        let lock = linked_lock(&mut rng, blocks, v1);
        let steps = seeded_steps(&lock, &mut rng);
        references += steps
            .iter()
            .filter(|(name, version, ..)| {
                lock.contains(&format!(" \"{name} {version} ({CRATES_IO})\""))
            })
            .count();
        repoint_both_ways(&lock, &steps);
    }
    assert!(
        references > 500,
        "the sweep repoints packages other blocks name by full id ({references})"
    );
    for lock in hand_written_locks() {
        for _ in 0..40 {
            let steps = seeded_steps(&lock, &mut rng);
            repoint_both_ways(&lock, &steps);
        }
    }
}

fn step(name: &str, version: &str, index: &'static str, cksum: &str) -> Step {
    (name.into(), version.into(), index, cksum.into(), true)
}

/// A package planned a second time is planned on the lock as its first
/// repoint left it, also when the second plan's splices are nowhere near
/// the first's. Here the first repoint changes the block alone; the second
/// one, read off the bytes as parsed, would see the block at its old index
/// and rewrite only the stray full id.
#[test]
fn a_package_planned_again_is_read_as_its_first_repoint_left_it() {
    let lock = format!(
        "version = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"p\",\n \"p 1.0.0 ({INDEX})\",\n]\n\n[[package]]\nname = \"p\"\nversion = \"1.0.0\"\nsource = \"{OTHER_INDEX}\"\nchecksum = \"aa\"\n"
    );
    let steps = [
        step("p", "1.0.0", INDEX, "bb"),
        step("p", "1.0.0", OTHER_INDEX, "aa"),
    ];
    assert_eq!(repoint_both_ways(&lock, &steps), 2);
}

/// A v1 lock with a stray `[metadata]` line for the id a repoint gives the
/// package: the repoint makes that key a duplicate and the lock stops
/// parsing. The crates after it are then refused, as they were when every
/// crate parsed the lock, and none is repointed on a lock cargo cannot
/// read.
#[test]
fn a_lock_a_repoint_leaves_unreadable_refuses_the_crates_after_it() {
    let lock = format!(
        "[[package]]\nname = \"p\"\nversion = \"1.0.0\"\nsource = \"{CRATES_IO}\"\n\n[[package]]\nname = \"q\"\nversion = \"2.0.0\"\nsource = \"{CRATES_IO}\"\n\n[metadata]\n\"checksum p 1.0.0 ({CRATES_IO})\" = \"aa\"\n\"checksum p 1.0.0 ({INDEX})\" = \"stale\"\n\"checksum q 2.0.0 ({CRATES_IO})\" = \"cc\"\n"
    );
    let mut held = CargoHostedLock::new(lock.clone());
    let CargoLockOutcome::Rewritten(planned) = held.plan("p", "1.0.0", INDEX, "bb") else {
        panic!("the first crate is repointed");
    };
    assert!(!held.commit(planned).is_empty());
    assert!(held.model().is_none(), "the lock no longer parses");
    assert!(matches!(
        held.plan("q", "2.0.0", INDEX, "dd"),
        CargoLockOutcome::NotFound
    ));
    repoint_both_ways(
        &lock,
        &[
            step("p", "1.0.0", INDEX, "bb"),
            step("q", "2.0.0", INDEX, "dd"),
        ],
    );
}

/// A lock of `count` crates with inline checksums, each depending on the
/// next: the shape cargo has written since 1.41.
fn chain_lock(count: usize) -> String {
    let mut lock = String::from("version = 4\n");
    for i in 0..count {
        lock.push_str(&format!(
            "\n[[package]]\nname = \"crate-{i}\"\nversion = \"1.0.{i}\"\nsource = \"{CRATES_IO}\"\n\
             checksum = \"{i:064x}\"\ndependencies = [\n \"crate-{}\",\n]\n",
            (i + 1) % count
        ));
    }
    lock
}

fn chain_step(i: usize, index: &'static str) -> Step {
    (
        format!("crate-{i}"),
        format!("1.0.{i}"),
        index,
        format!("{:064x}", i + 1000),
        true,
    )
}

/// What the one parse is for (#761): however many packages a rewrite
/// repoints, and whatever it finds already repointed or absent on the
/// way, it parses the lock once, where each package used to cost several
/// parses. A lock nothing reads is not parsed at all.
#[test]
fn a_rewrite_parses_the_lock_once() {
    let lock = chain_lock(200);
    let steps: Vec<Step> = (0..200).step_by(7).map(|i| chain_step(i, INDEX)).collect();
    assert_eq!(repoint_both_ways(&lock, &steps), 1);

    // A re-run that adds patches: crates already at their index and
    // crates to repoint, in turn, with an absent one among them.
    let (kind, redirected, _) = plan_on(&lock, "crate-3", "1.0.3", INDEX, "aa");
    assert_eq!(kind, "rewritten");
    let redirected = redirected.unwrap();
    let mixed = vec![
        chain_step(10, INDEX),
        ("crate-3".into(), "1.0.3".into(), INDEX, "aa".into(), true),
        chain_step(20, INDEX),
        (
            "absent-crate".into(),
            "9.9.9".into(),
            INDEX,
            "bb".into(),
            true,
        ),
        ("crate-3".into(), "1.0.3".into(), INDEX, "aa".into(), true),
        chain_step(30, INDEX),
    ];
    assert_eq!(repoint_both_ways(&redirected, &mixed), 1);

    // A package planned again reads the bytes its first repoint left: one
    // more parse, and no more than that for the packages after it.
    let mut again = steps.clone();
    again.insert(3, again[0].clone());
    assert_eq!(repoint_both_ways(&lock, &again), 2);
    let mut repinned = steps.clone();
    repinned.insert(3, chain_step(0, OTHER_INDEX));
    assert_eq!(repoint_both_ways(&lock, &repinned), 2);

    assert_eq!(CargoHostedLock::new(lock).parses(), 0);
}
