//! Rewrites of several crates in one run where a later crate's refusal
//! depends on what an earlier one did to `Cargo.lock`. The lock is parsed
//! once per rewrite ([`CargoHostedLock`]); these pin that each crate still
//! sees the lock as the crates before it left it, as it did when every
//! crate parsed the lock afresh.
//!
//! [`CargoHostedLock`]: crate::formats::cargo::hosted::CargoHostedLock

use std::collections::BTreeMap;

use super::{
    rewrite_cargo, rewrite_registry_redirect, DepOverride, Integrity, RegistryOverride,
    RegistryOverrideIdentifiers, RewriteResult,
};
use crate::formats::cargo::LOCK_PARSES;

const UUID_A: &str = "9f6b2c4e-1d3a-4f6b-8c2d-7e5a9b1c3d5f";
const UUID_B: &str = "1a2b3c4d-5e6f-4a7b-8c9d-0e1f2a3b4c5d";
const UUID_C: &str = "2b3c4d5e-6f7a-4b8c-9d0e-1f2a3b4c5d6e";
const UUID_D: &str = "3c4d5e6f-7a8b-4c9d-8e1f-2a3b4c5d6e7f";
const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

fn socket_index(uuid: &str) -> String {
    format!("sparse+https://patch.test/cargo/{uuid}/index/")
}

fn patch_of(name: &str, version: &str, uuid: &str, index_url: String) -> DepOverride {
    DepOverride {
        ecosystem: "cargo".into(),
        name: name.into(),
        namespace: None,
        version: version.into(),
        token: "tok".into(),
        patch_uuid: uuid.into(),
        artifact_url: format!("https://patch.test/{name}-{version}.crate"),
        npm_registry_url: None,
        registry_override: Some(RegistryOverride {
            kind: "cargo-sparse".into(),
            index_url,
            identifiers: RegistryOverrideIdentifiers {
                name: name.into(),
                version: version.into(),
                cargo_cksum_sha256: Some("e".repeat(64)),
                ..Default::default()
            },
        }),
        integrity: Integrity::default(),
    }
}

fn project(manifest: &str, lock: &str) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    files.insert("Cargo.toml".to_string(), manifest.to_string());
    files.insert("Cargo.lock".to_string(), lock.to_string());
    files
}

fn codes(result: &RewriteResult) -> Vec<&str> {
    result.warnings.iter().map(|w| w.code.as_str()).collect()
}

/// A crate vendored before any lock existed leaves a block with no
/// `source`, which a hosted pin gives one. A crate that block depends on
/// is then held by a registry package the pin cannot reach, and the
/// refusal says so: the block is read with the source the first repoint
/// gave it, not as the path package it was parsed as.
#[test]
fn a_dependent_repointed_earlier_in_the_run_is_read_with_its_new_source() {
    let manifest = "[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n\
                    [dependencies]\nouter = \"1.0.0\"\ninner = \"1.0.0\"\n";
    let lock = format!(
        "# This file is automatically @generated by Cargo.\nversion = 3\n\n\
         [[package]]\nname = \"app\"\nversion = \"0.1.0\"\n\
         dependencies = [\n \"inner\",\n \"outer\",\n]\n\n\
         [[package]]\nname = \"inner\"\nversion = \"1.0.0\"\nsource = \"{CRATES_IO}\"\n\
         checksum = \"{}\"\n\n\
         [[package]]\nname = \"outer\"\nversion = \"1.0.0\"\n\
         dependencies = [\n \"inner\",\n]\n",
        "a".repeat(64)
    );
    let result = rewrite_registry_redirect(
        &project(manifest, &lock),
        &[
            patch_of("outer", "1.0.0", UUID_A, socket_index(UUID_A)),
            patch_of("inner", "1.0.0", UUID_B, socket_index(UUID_B)),
        ],
    );
    assert_eq!(
        codes(&result),
        ["redirect_cargo_transitive_dependents"],
        "{:?}",
        result.warnings
    );
    let detail = &result.warnings[0].detail;
    assert!(
        detail.contains("outer 1.0.0 (registry)") && !detail.contains("path package"),
        "{detail}"
    );
    assert_eq!(
        result.confirmed_cargo_uuids.iter().collect::<Vec<_>>(),
        [UUID_A]
    );
    let rewritten = &result.files["Cargo.lock"];
    assert!(
        rewritten.contains(&format!(
            "name = \"outer\"\nversion = \"1.0.0\"\nsource = \"{}\"",
            socket_index(UUID_A)
        )),
        "{rewritten}"
    );
    assert!(
        rewritten.contains(&format!(
            "name = \"inner\"\nversion = \"1.0.0\"\nsource = \"{CRATES_IO}\""
        )),
        "{rewritten}"
    );
}

/// The same crate named by two patches, with index URLs that are not a
/// Socket per-patch index by their shape. The second is refused as an
/// override: it reads the lock entry at the registry the first one put it
/// on, which is no longer crates.io.
#[test]
fn a_second_patch_of_one_crate_reads_the_source_the_first_one_wrote() {
    let manifest = "[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n\
                    [dependencies]\nserde = \"1.0.190\"\n";
    let lock = format!(
        "# This file is automatically @generated by Cargo.\nversion = 3\n\n\
         [[package]]\nname = \"app\"\nversion = \"0.1.0\"\n\
         dependencies = [\n \"serde\",\n]\n\n\
         [[package]]\nname = \"serde\"\nversion = \"1.0.190\"\nsource = \"{CRATES_IO}\"\n\
         checksum = \"{}\"\n",
        "a".repeat(64)
    );
    let first = "sparse+https://patch.test/cargo/first/".to_string();
    let second = "sparse+https://patch.test/cargo/second/".to_string();
    let result = rewrite_registry_redirect(
        &project(manifest, &lock),
        &[
            patch_of("serde", "1.0.190", UUID_A, first.clone()),
            patch_of("serde", "1.0.190", UUID_B, second.clone()),
        ],
    );
    assert_eq!(
        codes(&result),
        ["redirect_cargo_dep_overridden"],
        "{:?}",
        result.warnings
    );
    assert_eq!(
        result.confirmed_cargo_uuids.iter().collect::<Vec<_>>(),
        [UUID_A]
    );
    let rewritten = &result.files["Cargo.lock"];
    assert!(
        rewritten.contains(&format!("source = \"{first}\"")) && !rewritten.contains(&second),
        "{rewritten}"
    );
    assert!(
        result.files["Cargo.toml"].contains(&format!("socket-patch-{UUID_A}"))
            && !result.files["Cargo.toml"].contains(UUID_B),
        "{}",
        result.files["Cargo.toml"]
    );
}

/// What the one parse is for (#761), through the Cargo rewrite itself: the
/// lock is parsed once however many crates are repointed, and not at all
/// by a rewrite that refuses before it reads the lock. The Cargo leg is
/// called directly: the whole rewrite runs each ecosystem on a thread of
/// its own, and the count is this thread's.
#[test]
fn the_rewrite_parses_the_lock_once() {
    let crates = [
        ("alpha", UUID_A),
        ("beta", UUID_B),
        ("delta", UUID_C),
        ("gamma", UUID_D),
    ];
    let mut manifest =
        String::from("[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n[dependencies]\n");
    let mut lock = String::from(
        "# This file is automatically @generated by Cargo.\nversion = 3\n\n\
         [[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n",
    );
    for (name, _) in crates {
        manifest.push_str(&format!("{name} = \"1.0.0\"\n"));
        lock.push_str(&format!(" \"{name}\",\n"));
    }
    lock.push_str("]\n");
    for (name, _) in crates {
        lock.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"1.0.0\"\nsource = \"{CRATES_IO}\"\n\
             checksum = \"{}\"\n",
            "a".repeat(64)
        ));
    }
    let files = project(&manifest, &lock);
    let patches: Vec<DepOverride> = crates
        .iter()
        .map(|(name, uuid)| patch_of(name, "1.0.0", uuid, socket_index(uuid)))
        .collect();

    let before = LOCK_PARSES.get();
    let mut result = RewriteResult::default();
    rewrite_cargo(&files, &patches, &mut result);
    let parses = LOCK_PARSES.get() - before;
    assert_eq!(codes(&result), [""; 0], "{:?}", result.warnings);
    assert_eq!(result.confirmed_cargo_uuids.len(), crates.len());
    for (_, uuid) in crates {
        assert!(
            result.files["Cargo.lock"].contains(&socket_index(uuid)),
            "{}",
            result.files["Cargo.lock"]
        );
    }
    assert_eq!(parses, 1, "one parse for {} repoints", crates.len());

    // No checksum for the patched crate: refused before the lock is read.
    let mut unusable = patch_of("alpha", "1.0.0", UUID_A, socket_index(UUID_A));
    if let Some(registry) = unusable.registry_override.as_mut() {
        registry.identifiers.cargo_cksum_sha256 = None;
    }
    let before = LOCK_PARSES.get();
    let mut result = RewriteResult::default();
    rewrite_cargo(&files, &[unusable], &mut result);
    let parses = LOCK_PARSES.get() - before;
    assert_eq!(
        codes(&result),
        ["redirect_cargo_missing_cksum"],
        "{:?}",
        result.warnings
    );
    assert_eq!(parses, 0, "a rewrite that never reads the lock");
}
