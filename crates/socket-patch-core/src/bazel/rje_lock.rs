/// Parses a whole document.
fn parse(text: &str) -> Result<Node, ReadError> {
    let mut parser = Parser {
        text,
        bytes: text.as_bytes(),
        at: 0,
    };
    let root = parser.value(0)?;
    parser.skip_space();
    if parser.at != parser.bytes.len() {
        return parser.fail("unexpected character after the value");
    }
    Ok(root)
}

struct Parser<'a> {
    text: &'a str,
    bytes: &'a [u8],
    at: usize,
}

impl Parser<'_> {
    fn fail<T>(&self, what: &'static str) -> Result<T, ReadError> {
        Err(ReadError::Syntax { at: self.at, what })
    }

    fn peek(&self) -> Option<u8> {
        self.bytes.get(self.at).copied()
    }

    /// The four characters Bazel's decoder skips.
    fn skip_space(&mut self) {
        while let Some(b' ' | b'\t' | b'\n' | b'\r') = self.peek() {
            self.at += 1;
        }
    }

    /// Consumes `byte` after any space.
    fn eat(&mut self, byte: u8) -> bool {
        self.skip_space();
        let found = self.peek() == Some(byte);
        self.at += usize::from(found);
        found
    }

    fn value(&mut self, depth: usize) -> Result<Node, ReadError> {
        self.skip_space();
        let start = self.at;
        if depth > MAX_DEPTH {
            return self.fail("nested too deeply");
        }
        let bytes = self.bytes;
        let rest = bytes.get(start..).unwrap_or_default();
        let value = match rest.first() {
            None => return self.fail("unexpected end of file"),
            Some(b'"') => Value::Str(self.string()?),
            Some(b'{') => Value::Object(self.object(depth)?),
            Some(b'[') => Value::Array(self.array(depth)?),
            Some(b'-' | b'0'..=b'9') => Value::Int(self.integer()?),
            Some(_) => {
                let literals = [
                    ("null", Value::Null),
                    ("true", Value::Bool(true)),
                    ("false", Value::Bool(false)),
                ];
                let found = literals
                    .into_iter()
                    .find(|(word, _)| rest.starts_with(word.as_bytes()));
                let Some((word, value)) = found else {
                    return self.fail("unexpected character");
                };
                self.at += word.len();
                value
            }
        };
        Ok(Node {
            span: (start, self.at),
            value,
        })
    }

    fn array(&mut self, depth: usize) -> Result<Vec<Node>, ReadError> {
        self.at += 1;
        let mut items = Vec::new();
        if self.eat(b']') {
            return Ok(items);
        }
        loop {
            items.push(self.value(depth + 1)?);
            if self.eat(b']') {
                return Ok(items);
            }
            if !self.eat(b',') {
                return self.fail("expected `,` or `]`");
            }
        }
    }

    fn object(&mut self, depth: usize) -> Result<Vec<Member>, ReadError> {
        let open = self.at;
        self.at += 1;
        let mut members = Vec::new();
        if self.eat(b'}') {
            return Ok(members);
        }
        loop {
            self.skip_space();
            let key_start = self.at;
            if self.peek() != Some(b'"') {
                return self.fail("an object key must be a string");
            }
            let key = self.string()?;
            let key_span = (key_start, self.at);
            if !self.eat(b':') {
                return self.fail("expected `:` after an object key");
            }
            let value = self.value(depth + 1)?;
            members.push(Member {
                key,
                key_span,
                value,
            });
            if self.eat(b'}') {
                break;
            }
            if !self.eat(b',') {
                return self.fail("expected `,` or `}`");
            }
        }
        let mut seen = HashSet::new();
        if !members.iter().all(|m| seen.insert(m.key.text.as_str())) {
            self.at = open;
            return self.fail("an object repeats a key");
        }
        Ok(members)
    }

    fn integer(&mut self) -> Result<String, ReadError> {
        let start = self.at;
        self.at += usize::from(self.peek() == Some(b'-'));
        let digits = self.at;
        while self.peek().is_some_and(|b| b.is_ascii_digit()) {
            self.at += 1;
        }
        let leading_zero = self.bytes[digits..self.at].starts_with(b"0") && self.at - digits > 1;
        let fraction = matches!(self.peek(), Some(b'.' | b'e' | b'E'));
        let literal = self.text.get(start..self.at).unwrap_or_default();
        if self.at == digits || leading_zero || fraction {
            // The error names where the number starts.
            self.at = start;
            let what = ["invalid number", "a number that is not an integer"];
            return self.fail(what[usize::from(fraction)]);
        }
        Ok(if literal == "-0" { "0" } else { literal }.to_string())
    }

    fn string(&mut self) -> Result<Text, ReadError> {
        self.at += 1;
        let (mut text, mut non_ascii_escape) = (String::new(), false);
        loop {
            let run = self.at;
            while self
                .peek()
                .is_some_and(|b| b != b'"' && b != b'\\' && b >= 0x20)
            {
                self.at += 1;
            }
            // Both ends are ASCII bytes or the end of the text, so the run
            // is whole characters.
            text.push_str(self.text.get(run..self.at).unwrap_or_default());
            match self.peek() {
                None => return self.fail("unclosed string"),
                Some(b'"') => {
                    self.at += 1;
                    return Ok(Text {
                        text,
                        non_ascii_escape,
                    });
                }
                Some(b'\\') => {
                    self.at += 1;
                    let c = self.escape()?;
                    non_ascii_escape |= !c.is_ascii();
                    text.push(c);
                }
                Some(_) => return self.fail("a control character in a string"),
            }
        }
    }

    /// The character an escape names; the backslash is consumed.
    fn escape(&mut self) -> Result<char, ReadError> {
        let Some(c) = self.peek() else {
            return self.fail("incomplete escape");
        };
        self.at += 1;
        Ok(match c {
            b'"' | b'\\' | b'/' => char::from(c),
            b'b' => '\u{8}',
            b'f' => '\u{c}',
            b'n' => '\n',
            b'r' => '\r',
            b't' => '\t',
            b'u' => {
                let unit = self.hex4()?;
                let code = match unit {
                    0xD800..=0xDBFF if self.bytes[self.at..].starts_with(b"\\u") => {
                        self.at += 2;
                        match self.hex4()? {
                            low @ 0xDC00..=0xDFFF => {
                                0x10000 + ((unit - 0xD800) << 10) + (low - 0xDC00)
                            }
                            _ => return self.fail("a lone surrogate in a string"),
                        }
                    }
                    unit => unit,
                };
                match char::from_u32(code) {
                    Some(c) => c,
                    None => return self.fail("a lone surrogate in a string"),
                }
            }
            _ => {
                self.at -= 1;
                return self.fail("invalid escape");
            }
        })
    }

    fn hex4(&mut self) -> Result<u32, ReadError> {
        let mut unit = 0;
        for _ in 0..4 {
            let Some(digit) = self.peek().and_then(|b| char::from(b).to_digit(16)) else {
                return self.fail("invalid `\\u` escape");
            };
            unit = unit * 16 + digit;
            self.at += 1;
        }
        Ok(unit)
    }
}

