//! The build file that cargo-bazel, the tool of rules_rust's crate hubs,
//! writes into a crate a Cargo workspace takes from a path.
//!
//! Vendored mode keeps a patched crate under `.socket/vendor/cargo` and
//! points a `[patch.crates-io]` path entry at it. From rules_rust 0.59.0 on,
//! cargo-bazel renders the build file of such a crate to
//! `<crate>/BUILD.bazel` in the checkout, each time Bazel evaluates the hub
//! (`crate_universe/src/rendering.rs`, `render_build_files`). The scan
//! recorded no such file, so the copy would read as a changed one after a
//! build that is the patched one.
//!
//! A hub (`crate.from_cargo`) does not build the crate from that file: it
//! copies the directory into a repository of its own and renders the build
//! file of that repository again
//! (`crate_universe/private/local_crate_mirror.bzl`; measured on Bazel
//! 9.3.2, 8.8.2 and 7.7.2, where another file under the same banner left
//! the build as it was). Bazel still reads the file in the checkout as a
//! package of the workspace, and that package names repositories only the
//! hub sees: for a crate with a dependency `bazel cquery //...` and
//! `bazel query 'deps(//...)'` fail on it. So where the module files of
//! the workspace make such a hub ([`hub`]), the file is no change of the
//! copy ([`wrote_build_file`]) and the copies get a `.bazelignore` line
//! ([`super::ignore`]).
//!
//! Nowhere else. Read in the same source and not run: where `crates_vendor`
//! renders build files into the checkout (`mode = "local"`), they name such
//! a crate by that package, so there the file is the one the crate is built
//! from and a `.bazelignore` line would take the crate away from the build.

use std::io::Read as _;
use std::path::Path;

use super::workspace::{disk, Extension, Workspace};
use crate::utils::fs::{open_regular_file_sync, run_blocking};

/// Where vendored mode keeps its crates, from the project.
pub(crate) const VENDOR_DIR: &str = ".socket/vendor/cargo";

/// The name of that file, in the directory of the crate.
pub(crate) const BUILD_FILE: &str = "BUILD.bazel";

/// How every file cargo-bazel renders begins: the first three lines of its
/// banner, the third up to the name of the tool (`partials/header.j2`,
/// unchanged since 2022). The command that renders the file again follows.
const BANNER: [&str; 3] = [
    "###############################################################################",
    "# @generated",
    "# DO NOT MODIFY: This file is auto-generated by a crate_universe tool.",
];

/// The files of rules_rust that define the extension of its crate hubs:
/// the one its documentation names, and the older name it still takes.
const EXTENSION_FILES: [&str; 2] = [
    "//crate_universe:extensions.bzl",
    "//crate_universe:extension.bzl",
];

/// Whether the module files of the Bazel workspace at `root` call
/// `crate.from_cargo`, the tag that makes a hub from a Cargo workspace.
/// Any such call counts, whichever manifests it names: this is asked of a
/// workspace that holds a vendored crate, to tell what may have written
/// into it. A hub of the older `WORKSPACE` system is not looked for.
pub(crate) fn hub(root: &Path) -> bool {
    let workspace = Workspace::read(&disk(root));
    EXTENSION_FILES.iter().any(|file| {
        let (module, name) = ("rules_rust", "crate");
        let extension = Extension { module, file, name };
        !workspace.tags(&extension, "from_cargo").calls.is_empty()
    })
}

/// Whether the [`BUILD_FILE`] of `crate_dir`, a crate of the project at
/// `project`, is one cargo-bazel wrote: a file that begins with [`BANNER`],
/// in a project whose Bazel workspace ([`super::bazel_root`]) has a crate
/// [`hub`]. The banner says which tool the file names as its writer. It
/// does not vouch for the rest of the file, which differs from one machine
/// to the next. A link is followed: the one caller asks about a file that
/// its own walk of the copy found to be a regular one.
pub(crate) async fn wrote_build_file(project: &Path, crate_dir: &Path) -> bool {
    let (project, file) = (project.to_path_buf(), crate_dir.join(BUILD_FILE));
    run_blocking(move || {
        // What cannot be read has no banner.
        let mut start = Vec::new();
        let _ = open_regular_file_sync(&file)
            .and_then(|(file, _)| file.take(512).read_to_end(&mut start));
        let start = String::from_utf8_lossy(&start);
        let mut lines = start.lines();
        BANNER[..2].iter().all(|line| lines.next() == Some(line))
            && lines.next().is_some_and(|line| line.starts_with(BANNER[2]))
            && super::bazel_root(&project).is_some_and(|root| hub(&root.dir))
    })
    .await
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use std::fs;

    /// A `MODULE.bazel` with the hub of the rules_rust README.
    pub(crate) const HUB: &str = "bazel_dep(name = \"rules_rust\", version = \"0.75.0\")\n\
        crate = use_extension(\"@rules_rust//crate_universe:extensions.bzl\", \"crate\")\n\
        crate.from_cargo(\n    name = \"crates\",\n    cargo_lockfile = \"//:Cargo.lock\",\n    \
        manifests = [\"//:Cargo.toml\"],\n)\n\
        use_repo(crate, \"crates\")\n";

    /// A checkout with the file `marks` at its root, which holds `module`,
    /// and a crate in `krate`, whose build file holds `text`.
    fn checkout(marks: &str, module: &str, text: &str) -> tempfile::TempDir {
        let tmp = tempfile::tempdir().unwrap();
        fs::create_dir_all(tmp.path().join(".git")).unwrap();
        fs::create_dir_all(tmp.path().join("krate")).unwrap();
        fs::write(tmp.path().join(marks), module).unwrap();
        fs::write(tmp.path().join("krate").join(BUILD_FILE), text).unwrap();
        tmp
    }

    async fn wrote(marks: &str, module: &str, text: &str) -> bool {
        let tmp = checkout(marks, module, text);
        wrote_build_file(tmp.path(), &tmp.path().join("krate")).await
    }

    /// The first lines of the file a build on rules_rust 0.75.0 wrote into
    /// a vendored crate (Bazel 9.3.2).
    const WRITTEN: &str =
        "###############################################################################\n\
        # @generated\n\
        # DO NOT MODIFY: This file is auto-generated by a crate_universe tool. To \n\
        # regenerate this file, run the following:\n\
        #\n\
        #     bazel mod show_repo 'socket_fixture'\n\
        ###############################################################################\n\
        \n\
        load(\"@rules_rust//rust:defs.bzl\", \"rust_library\")\n";

    #[tokio::test]
    async fn only_a_file_under_the_banner_in_a_workspace_with_a_crate_hub_is_cargo_bazels() {
        const MODULE: &str = "MODULE.bazel";
        assert!(wrote(MODULE, HUB, WRITTEN).await);
        assert!(wrote(MODULE, HUB, &WRITTEN.replace('\n', "\r\n")).await);
        // Each line of the banner is needed, in its place, from the start
        // of the file.
        let lines: Vec<&str> = WRITTEN.split_inclusive('\n').collect();
        for missing in 0..3 {
            let mut left = lines.clone();
            left.remove(missing);
            assert!(!wrote(MODULE, HUB, &left.concat()).await, "{missing}");
        }
        // And each line is the banner's own.
        for other in [
            String::new(),
            format!("\n{WRITTEN}"),
            format!("# mine\n{WRITTEN}"),
            WRITTEN.replacen('#', "", 1),
            WRITTEN.replace("# @generated", "# @generated by hand"),
            WRITTEN.replace("crate_universe tool", "tool"),
            "genrule(name = \"x\")\n".to_string(),
        ] {
            assert!(!wrote(MODULE, HUB, &other).await, "{other:?}");
        }
        // No Bazel workspace, or one whose module files make no such hub:
        // the file is then nobody's.
        assert!(!wrote("Cargo.toml", HUB, WRITTEN).await);
        for module in [
            "",
            "bazel_dep(name = \"rules_rust\", version = \"0.75.0\")\n",
            &HUB.replace("from_cargo", "from_specs"),
            &HUB.replace("@rules_rust//", "@rules_mine//"),
            &HUB.replace("extensions.bzl", "other.bzl"),
            &HUB.replace("\"crate\")", "\"other\")"),
        ] {
            assert!(!wrote(MODULE, module, WRITTEN).await, "{module}");
        }
        assert!(!wrote("WORKSPACE", HUB, WRITTEN).await);
        // The hub under the older name of its file, under another name for
        // the ruleset, and in a file the root includes.
        let renamed = HUB
            .replace("0.75.0\")", "0.75.0\", repo_name = \"rr\")")
            .replace("@rules_rust//", "@rr//");
        for module in [HUB.replace("extensions.bzl", "extension.bzl"), renamed] {
            assert!(wrote(MODULE, &module, WRITTEN).await, "{module}");
        }
        let tmp = checkout(MODULE, "include(\"//:rust.MODULE.bazel\")\n", WRITTEN);
        fs::write(tmp.path().join("rust.MODULE.bazel"), HUB).unwrap();
        assert!(wrote_build_file(tmp.path(), &tmp.path().join("krate")).await);
    }
}
