/// A user `yarn patch` on top of Socket's hosted patch: yarn keeps the
/// hosted base entry and adds a `patch:` entry wrapping its locator. The
/// `patch:` entry is not Socket's (silently skipped); the base entry is,
/// and the installed tree (base + the user's patch) decides.
#[test]
fn user_yarn_patch_on_top_of_hosted() {
    let tmp = tempfile::tempdir().unwrap();
    let cwd = tmp.path();
    project(
        cwd,
        serde_json::json!({ "left-pad": "patch:left-pad@npm%3A1.3.0#~/.yarn/patches/left-pad-npm-1.3.0-0123456789.patch" }),
        None,
    );
    let url = hosted_url(SOCKET, UUID, "left-pad-1.3.0.tgz");
    let inner = format!("npm:1.3.0::__archiveUrl={}", enc(&url));
    let patch_block = format!(
        "\"left-pad@patch:left-pad@npm%3A1.3.0#~/.yarn/patches/left-pad-npm-1.3.0-0123456789.patch\":\n  \
         version: 1.3.0\n  resolution: \"left-pad@patch:left-pad@{}#~/.yarn/patches/left-pad-npm-1.3.0-0123456789.patch::version=1.3.0&hash=abcdef\"\n  \
         checksum: {}\n  languageName: node\n  linkType: hard\n\n",
        enc(&inner),
        checksum('5')
    );
    put(
        cwd,
        "yarn.lock",
        format!(
            "{}{}{}{}",
            header(),
            workspace_block(
                "app",
                ".",
                &[(
                    "left-pad",
                    "patch:left-pad@npm%3A1.3.0#~/.yarn/patches/left-pad-npm-1.3.0-0123456789.patch"
                )]
            ),
            hosted_block("left-pad@npm:1.3.0", "left-pad", "1.3.0", &url),
            patch_block
        )
        .as_bytes(),
    );
    let api = api_for(LP);
    // The user's patch touched another file: the Socket-patched file is
    // intact in the installed tree.
    install_at(cwd, "node_modules/left-pad", "left-pad", "1.3.0", PATCHED);
    put(
        cwd,
        "node_modules/left-pad/README.md",
        b"user-patched readme\n",
    );
    let out = run_vex(&binary(), cwd, &VexRun::online(&api));
    attested(&out, LP, Marker::Redirected, "user patch elsewhere");
    // The user's patch rewrote the Socket-patched file: not attested.
    install_at(
        cwd,
        "node_modules/left-pad",
        "left-pad",
        "1.3.0",
        b"/* user yarn patch */\nmodule.exports = 1;\n",
    );
    let out = run_vex(&binary(), cwd, &VexRun::online(&api));
    omitted(&out, LP, "hash_mismatch", "user patch rewrote the file");
}

// ── spoofing ─────────────────────────────────────────────────────────────

/// An `__archiveUrl` that is not on the Socket patch host — including
/// look-alikes — or whose uuid-shaped segments are only a GRANT TOKEN of
/// the patch host's path grammar, is never a patch reference: nothing is
/// discovered and nothing is fetched.
#[test]
fn foreign_hosts_and_token_only_urls_are_not_references() {
    let api = api_for(LP);
    for url in [
        hosted_url("https://evil.example", UUID, "left-pad-1.3.0.tgz"),
        hosted_url(
            "https://patch.socket.dev.evil.example",
            UUID,
            "left-pad-1.3.0.tgz",
        ),
        hosted_url(
            "https://patch.socket.dev@evil.example",
            UUID,
            "left-pad-1.3.0.tgz",
        ),
        hosted_url(
            "http://patch.socket.dev:8080.evil.example",
            UUID,
            "left-pad-1.3.0.tgz",
        ),
        // The uuid only in a query string / fragment of a foreign URL.
        format!("https://evil.example/left-pad-1.3.0.tgz?patch={UUID}"),
        format!("https://evil.example/left-pad-1.3.0.tgz#{UUID}"),
    ] {
        let tmp = tempfile::tempdir().unwrap();
        let cwd = tmp.path();
        project(cwd, serde_json::json!({ "left-pad": "1.3.0" }), None);
        put(cwd, "yarn.lock", lp_hosted_lock(&url).as_bytes());
        install_at(cwd, "node_modules/left-pad", "left-pad", "1.3.0", PATCHED);
        let before = api.request_count();
        let out = run_vex(&binary(), cwd, &VexRun::online(&api));
        nothing_discovered(&out, &url);
        assert_eq!(api.request_count(), before, "{url}: network call made");
    }
}
