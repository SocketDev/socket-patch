//! A Cargo project whose `Cargo.lock` takes `cfg-if 1.0.4` from crates.io,
//! a `[patch.crates-io]` path override or a git dependency, beside a
//! crates.io copy of the crate in `$CARGO_HOME/registry/src` (#506). Shared
//! by the `apply` and `vex` suites; pull it in with
//! `#[path = "common/cargo_lock_source.rs"] mod cargo_lock_source;`.

#![allow(dead_code)]

use std::path::{Path, PathBuf};

pub const PURL: &str = "pkg:cargo/cfg-if@1.0.4";
pub const BEFORE: &[u8] = b"pub fn upstream() -> u32 { 1 }\n";
pub const AFTER: &[u8] = b"pub fn upstream() -> u32 { 1 }\npub fn socket_patched() {}\n";
pub const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// Where cargo builds `cfg-if` from in the project.
#[derive(Clone, Copy, Debug)]
pub enum Shape {
    /// `cfg-if = "=1.0.4"` from crates.io: the registry copy is the build's.
    Registry,
    /// `[patch.crates-io] cfg-if = { path = "local/cfg-if" }` in `Cargo.toml`.
    ManifestPatch,
    /// The same `[patch.crates-io]` in `.cargo/config.toml`.
    ConfigPatch,
    /// `cfg-if = { git = "file:///…" }`, no `[patch]` at all.
    GitDependency,
    /// `cfg-if = { path = "local/cfg-if" }`, no `[patch]` at all.
    PathDependency,
}

/// A crates.io copy of `cfg-if-1.0.4` in `<cargo_home>/registry/src`,
/// holding `lib`. Returns the copy's `src/lib.rs`.
pub fn stage_registry_copy(cargo_home: &Path, lib: &[u8]) -> PathBuf {
    let dir = cargo_home.join("registry/src/index.crates.io-1949cf8c6b5b557f/cfg-if-1.0.4");
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("Cargo.toml"),
        "[package]\nname = \"cfg-if\"\nversion = \"1.0.4\"\nedition = \"2018\"\n",
    )
    .unwrap();
    std::fs::write(dir.join("src/lib.rs"), lib).unwrap();
    dir.join("src/lib.rs")
}

/// A binary crate depending on `cfg-if 1.0.4` the way `shape` says, with
/// the `Cargo.lock` cargo writes for it.
pub fn write_project(root: &Path, shape: Shape) {
    let dep = match shape {
        Shape::GitDependency => "cfg-if = { git = \"file:///srv/git/cfg-if\" }",
        Shape::PathDependency => "cfg-if = { path = \"local/cfg-if\" }",
        _ => "cfg-if = \"=1.0.4\"",
    };
    let mut manifest = format!(
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
         [dependencies]\n{dep}\n"
    );
    let patch = "[patch.crates-io]\ncfg-if = { path = \"local/cfg-if\" }\n";
    match shape {
        Shape::ManifestPatch => manifest.push_str(&format!("\n{patch}")),
        Shape::ConfigPatch => {
            std::fs::create_dir_all(root.join(".cargo")).unwrap();
            std::fs::write(root.join(".cargo/config.toml"), patch).unwrap();
        }
        Shape::Registry | Shape::GitDependency | Shape::PathDependency => {}
    }
    if matches!(
        shape,
        Shape::ManifestPatch | Shape::ConfigPatch | Shape::PathDependency
    ) {
        let fork = root.join("local/cfg-if");
        std::fs::create_dir_all(fork.join("src")).unwrap();
        std::fs::write(
            fork.join("Cargo.toml"),
            "[package]\nname = \"cfg-if\"\nversion = \"1.0.4\"\nedition = \"2018\"\n",
        )
        .unwrap();
        std::fs::write(fork.join("src/lib.rs"), "pub fn user_fork() -> u32 { 7 }\n").unwrap();
    }
    std::fs::write(root.join("Cargo.toml"), manifest).unwrap();

    let source = match shape {
        Shape::Registry => format!(
            "source = \"{CRATES_IO}\"\nchecksum = \
             \"9330f8b2ff13f34540b44e946ef35111825727b38d33286ef986142615121801\"\n"
        ),
        Shape::ManifestPatch | Shape::ConfigPatch | Shape::PathDependency => String::new(),
        Shape::GitDependency => "source = \"git+file:///srv/git/cfg-if#\
             0123456789abcdef0123456789abcdef01234567\"\n"
            .to_string(),
    };
    std::fs::write(
        root.join("Cargo.lock"),
        format!(
            "# This file is automatically @generated by Cargo.\n\
             # It is not intended for manual editing.\n\
             version = 4\n\n\
             [[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"cfg-if\",\n]\n\n\
             [[package]]\nname = \"cfg-if\"\nversion = \"1.0.4\"\n{source}"
        ),
    )
    .unwrap();
    std::fs::create_dir_all(root.join("src")).unwrap();
    std::fs::write(root.join("src/main.rs"), "fn main() {}\n").unwrap();
}
